import { NodeServices } from '@effect/platform-node';
import { Effect, FileSystem, ManagedRuntime, Path, Schema } from 'effect';
import { Command, Flag } from 'effect/cli';

import { OUTBOX_WORKER_HOST, outboxWorkerHostDelivery } from './outbox-worker-delivery.mjs';
import { readDevelopmentPorts } from './topology-development-ports.mjs';

/** Readiness port of the combined host; it must not collide with any topology vertical port. */
export const OUTBOX_WORKER_HOST_HEALTH_PORT = '4100';

/**
 * The module the host entry reads its artifact digest from. The host bundle compiles the plan's digest in
 * its place, so /status names the exact prebuilt artifact; a source run of the entry reports none.
 */
export const OUTBOX_HOST_ARTIFACT_MODULE = 'scripts/outbox-worker-host-artifact.mts';

const TopologySchema = Schema.fromJsonString(
  Schema.Struct({
    shell: Schema.Struct({ id: Schema.String, package: Schema.String, path: Schema.String }),
    verticals: Schema.Array(
      Schema.Struct({
        id: Schema.String,
        package: Schema.String,
        path: Schema.String,
      }),
    ),
  }),
);

class OutboxWorkerDeploymentError extends Error {
  /** @param {string} message Error detail. */
  constructor(message) {
    super(message);
    this.name = 'OutboxWorkerDeploymentError';
    this._tag = 'OutboxWorkerDeploymentError';
  }
}

/** @param {string} message Error detail. */
const failure = (message) => new OutboxWorkerDeploymentError(message);

const nodeRuntime = ManagedRuntime.make(NodeServices.layer);

const RootPackageSchema = Schema.fromJsonString(
  Schema.Struct({
    dependencies: Schema.optionalKey(Schema.Record(Schema.String, Schema.String)),
    name: Schema.String,
  }),
);
const CORE_WORKER_PACKAGE = '@app/core-runtime';
const HOST_ENTRY_HEADER =
  '// @generated by scripts/generate-outbox-worker-deployment.mjs from topology and Outbox Worker delivery discovery';

/** @param {string} id Topology identifier. */
const camelCase = (id) => id.replaceAll(/-(?<letter>[a-z0-9])/gu, (_match, letter) => String(letter).toUpperCase());

/**
 * @param {string} root Workspace root.
 * @returns {Effect.Effect<import('./outbox-worker-delivery.mjs').OutboxWorkerHostDelivery | undefined, OutboxWorkerDeploymentError | Schema.SchemaError | import('effect/PlatformError').PlatformError, FileSystem.FileSystem | Path.Path>} Hosted worker owners in topology order.
 */
export const readOutboxWorkerHost = (root) =>
  Effect.gen(function* readHost() {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const topology = yield* Schema.decodeUnknownEffect(TopologySchema)(
      yield* fs.readFileString(path.join(root, 'topology/reference-topology.json')),
    );
    const ports = yield* readDevelopmentPorts(root);
    for (const vertical of topology.verticals) {
      const port = String(ports[vertical.id] ?? '');
      if (port === OUTBOX_WORKER_HOST_HEALTH_PORT) {
        return yield* Effect.fail(failure(`${vertical.id} uses the Outbox Worker host health port`));
      }
    }
    return yield* outboxWorkerHostDelivery(root, topology.verticals, topology.shell).pipe(
      Effect.mapError(() => failure('Invalid generated Outbox Worker delivery')),
    );
  });

/**
 * The host entry imports every owner's generated Outbox Worker entry and runs them in one process.
 * Its source is already in the formatter's shape: one import per line and one entry per array line.
 * @param {import('./outbox-worker-delivery.mjs').OutboxWorkerHostDelivery} host Hosted worker owners.
 * @returns {string} Host entry source.
 */
export const renderOutboxWorkerHostEntry = (host) => {
  const bindings = host.owners.map((owner) => `${camelCase(owner.ownerId)}OutboxWorkerEntry`);
  return [
    HOST_ENTRY_HEADER,
    "import { startEmailDispatchTrigger } from './email-dispatch-trigger.mts';",
    "import { outboxHostArtifactDigest } from './outbox-worker-host-artifact.mts';",
    "import { startOutboxWorkerHost } from '@app/core-runtime/outbox/worker';",
    `import { outboxWorkerEntry as coreSystemOutboxWorkerEntry } from '${host.coreOwner.hostExport}';`,
    ...host.owners.map(
      (owner, index) => `import { outboxWorkerEntry as ${bindings[index] ?? ''} } from '${owner.hostExport}';`,
    ),
    '',
    'startOutboxWorkerHost({',
    '  artifactDigest: outboxHostArtifactDigest,',
    '  entries: [',
    '    coreSystemOutboxWorkerEntry,',
    ...bindings.map((binding) => `    ${binding},`),
    '  ],',
    '  health: true,',
    '  startup: startEmailDispatchTrigger,',
    '});',
    '',
  ].join('\n');
};

/**
 * @param {string} root Workspace root.
 * @returns {Effect.Effect<string | null, OutboxWorkerDeploymentError | Schema.SchemaError | import('effect/PlatformError').PlatformError, FileSystem.FileSystem | Path.Path>} Host entry source, or null when no owner is hosted.
 */
const generateOutboxWorkerHostEntryEffect = (root) =>
  Effect.gen(function* generateHostEntry() {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const host = yield* readOutboxWorkerHost(root);
    if (host === undefined) {
      return null;
    }
    const rootPackage = yield* Schema.decodeUnknownEffect(RootPackageSchema)(
      yield* fs.readFileString(path.join(root, 'package.json')),
    );
    // The host reaches every owner only through the package export that owner publishes, so the
    // workspace root must depend on each hosted owner package and on the Core worker entrypoint.
    const missingDependencies = [
      CORE_WORKER_PACKAGE,
      host.coreOwner.packageName,
      ...host.owners.map((owner) => owner.packageName),
    ].filter((name) => rootPackage.dependencies?.[name] !== 'workspace:*');
    if (missingDependencies.length > 0) {
      return yield* Effect.fail(
        failure(`The workspace root must depend on ${missingDependencies.join(', ')} as workspace:*`),
      );
    }
    return renderOutboxWorkerHostEntry(host);
  });

/**
 * @param {string} root Workspace root.
 * @returns {PromiseLike<string | null>} Outbox Worker host entry source, or null when no owner is hosted.
 */
export const generateOutboxWorkerHostEntry = (root) =>
  nodeRuntime.runPromise(generateOutboxWorkerHostEntryEffect(root));

/** @param {{ write: boolean }} options Parsed command options. */
const runCommand = ({ write }) =>
  Effect.gen(function* runHostEntryGenerator() {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const root = path.resolve();
    const hostEntryFile = path.join(root, OUTBOX_WORKER_HOST.entry);
    const currentHostEntry = (yield* fs.exists(hostEntryFile)) ? yield* fs.readFileString(hostEntryFile) : null;
    const generated = yield* generateOutboxWorkerHostEntryEffect(root);
    if (write) {
      yield* generated === null
        ? fs.remove(hostEntryFile, { force: true })
        : fs.writeFileString(hostEntryFile, generated);
    } else if (currentHostEntry !== generated) {
      yield* Effect.fail(
        failure('Outbox Worker host entry drift: run node scripts/generate-outbox-worker-deployment.mjs --write'),
      );
    }
  });

const command = Command.make(
  'generate-outbox-worker-deployment',
  { write: Flag.Boolean('write').pipe(Flag.withDefault(false)) },
  runCommand,
);

if (import.meta.main) {
  void nodeRuntime.runPromise(Command.run(command, { version: '1.0.0' }));
}
