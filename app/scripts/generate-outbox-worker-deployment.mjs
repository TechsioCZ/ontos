import { NodeServices } from '@effect/platform-node';
import { Array as Arr, Effect, FileSystem, ManagedRuntime, Order, Path, Schema } from 'effect';
import { Command, Flag } from 'effect/unstable/cli';

import { OUTBOX_WORKER_HOST, outboxWorkerDelivery, outboxWorkerHostDelivery } from './outbox-worker-delivery.mjs';

/** Readiness port of the combined host; it must not collide with any topology vertical port. */
export const OUTBOX_WORKER_HOST_HEALTH_PORT = '4100';

const TopologySchema = Schema.fromJsonString(
  Schema.Struct({
    verticals: Schema.Array(
      Schema.Struct({
        id: Schema.String,
        moduleFederation: Schema.Struct({ manifestUrl: Schema.String }),
        package: Schema.String,
        path: Schema.String,
      }),
    ),
  }),
);

class OutboxWorkerDeploymentError extends Error {
  /** @param {string} message Error detail. */
  constructor(message) {
    super(message);
    this.name = 'OutboxWorkerDeploymentError';
    this._tag = 'OutboxWorkerDeploymentError';
  }
}

/** @param {string} message Error detail. */
const failure = (message) => new OutboxWorkerDeploymentError(message);

const nodeRuntime = ManagedRuntime.make(NodeServices.layer);

const RootPackageSchema = Schema.fromJsonString(Schema.Struct({ name: Schema.String }));
const HOST_ENTRY_HEADER =
  '// @generated by scripts/generate-outbox-worker-deployment.mjs from topology and Outbox Worker delivery discovery';
// Every hosted owner's worker declares these for itself; the host declares its own.
const OWNER_SPECIFIC_ENVIRONMENT = new Set(['OUTBOX_WORKER_HEALTH_PORT', 'PORT', 'ULTRAMODERN_ZEROPS_SERVICE']);

/** @param {string} id Topology identifier. */
const camelCase = (id) => id.replaceAll(/-(?<letter>[a-z0-9])/gu, (_match, letter) => String(letter).toUpperCase());

/**
 * @param {string} root Workspace root.
 * @returns {Effect.Effect<import('./outbox-worker-delivery.mjs').OutboxWorkerHostDelivery | undefined, OutboxWorkerDeploymentError | Schema.SchemaError | import('effect/PlatformError').PlatformError, FileSystem.FileSystem | Path.Path>} Hosted worker owners in topology order.
 */
export const readOutboxWorkerHost = (root) =>
  Effect.gen(function* readHost() {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const topology = yield* Schema.decodeUnknownEffect(TopologySchema)(
      yield* fs.readFileString(path.join(root, 'topology/reference-topology.json')),
    );
    for (const vertical of topology.verticals) {
      const port = yield* Effect.try({
        catch: () => failure(`Invalid topology manifest URL for ${vertical.id}`),
        try: () => new URL(vertical.moduleFederation.manifestUrl).port,
      });
      if (port === OUTBOX_WORKER_HOST_HEALTH_PORT) {
        return yield* Effect.fail(failure(`${vertical.id} uses the Outbox Worker host health port`));
      }
    }
    return yield* outboxWorkerHostDelivery(root, topology.verticals).pipe(
      Effect.mapError(() => failure('Invalid generated Outbox Worker delivery')),
    );
  });

/**
 * The host entry imports every owner's generated Outbox Worker entry and runs them in one process.
 * Its source is already in the formatter's shape: one import per line and one entry per array line.
 * @param {import('./outbox-worker-delivery.mjs').OutboxWorkerHostDelivery} host Hosted worker owners.
 * @returns {string} Host entry source.
 */
export const renderOutboxWorkerHostEntry = (host) => {
  const bindings = host.owners.map((owner) => `${camelCase(owner.ownerId)}OutboxWorkerEntry`);
  return [
    HOST_ENTRY_HEADER,
    "import { startOutboxWorkerHost } from '../packages/core-runtime/src/outbox/worker-entrypoint.ts';",
    ...host.owners.map(
      (owner, index) =>
        `import { outboxWorkerEntry as ${bindings[index] ?? ''} } from '../${owner.path}/${owner.hostEntry}';`,
    ),
    '',
    'startOutboxWorkerHost({',
    '  entries: [',
    ...bindings.map((binding) => `    ${binding},`),
    '  ],',
    '  health: true,',
    '});',
    '',
  ].join('\n');
};

/**
 * @param {string} service Generated worker service section.
 * @returns {Map<string, string>} Worker run environment.
 */
const runEnvironment = (service) => {
  const block =
    /\n {6}envVariables:\n(?<lines>(?: {8}[^\n]*\n)+)/u.exec(`${service.slice(service.indexOf('\n    run:\n'))}\n`)
      ?.groups?.lines ?? '';
  /** @type {Map<string, string>} */
  const environment = new Map();
  for (const match of block.matchAll(/^ {8}(?<key>[A-Z][A-Z0-9_]*): (?<value>.*)$/gmu)) {
    const { key, value } = match.groups ?? {};
    if (key !== undefined && value !== undefined) {
      environment.set(key, value);
    }
  }
  return environment;
};

/**
 * @param {string} service Generated worker service section.
 * @returns {string} Start preflight that must still guard the hosted worker.
 */
const startPreflight = (service) =>
  /^ {6}start: sh -c '(?<preflight>.*?)cd app\//mu.exec(service)?.groups?.preflight ?? '';

/**
 * One service runs every owner's entry: the build of the first dedicated worker, the union of their
 * start preflights, and their shared run environment, which must agree on every shared key.
 * @param {readonly string[]} services Generated dedicated worker services, in topology order.
 * @param {readonly string[]} serviceIds Their setups.
 * @param {string} rootPackageName Workspace root package name.
 */
const renderHostService = (services, serviceIds, rootPackageName) =>
  Effect.gen(function* renderHostServiceEffect() {
    /** @type {Map<string, string>} */
    const environment = new Map([
      ['OUTBOX_WORKER_HEALTH_PORT', `'${OUTBOX_WORKER_HOST_HEALTH_PORT}'`],
      ['PORT', `'${OUTBOX_WORKER_HOST_HEALTH_PORT}'`],
      ['ULTRAMODERN_ZEROPS_SERVICE', OUTBOX_WORKER_HOST.id],
    ]);
    /** @type {Set<string>} */
    const preflights = new Set();
    for (const [index, service] of services.entries()) {
      for (const [key, value] of runEnvironment(service)) {
        if (OWNER_SPECIFIC_ENVIRONMENT.has(key)) {
          continue;
        }
        const current = environment.get(key);
        if (current !== undefined && current !== value) {
          return yield* Effect.fail(
            failure(`Hosted Outbox Worker owners disagree on ${key} (${serviceIds[index] ?? ''})`),
          );
        }
        environment.set(key, value);
      }
      preflights.add(startPreflight(service));
    }
    const [template] = services;
    const [templateId] = serviceIds;
    if (template === undefined || templateId === undefined) {
      return yield* Effect.fail(failure('The Outbox Worker host has no owners'));
    }
    const runStart = template.indexOf('\n    run:\n');
    const runtimeDir = `app/.zerops/runtime/${OUTBOX_WORKER_HOST.id}`;
    const buildAndDeploy = template
      .slice(0, runStart)
      .replace(`setup: '${templateId}'`, `setup: '${OUTBOX_WORKER_HOST.stageSetup}'`)
      .replaceAll(`app/.zerops/runtime/${templateId}`, runtimeDir)
      .replace(
        /--app '[^']*' --package '[^']*' --package-dir '[^']*' --worker/u,
        `--app '${OUTBOX_WORKER_HOST.id}' --package '${rootPackageName}' --package-dir '.' --worker`,
      )
      .replace(/^(?<key> {10}port: )[0-9]+$/mu, `$<key>${OUTBOX_WORKER_HOST_HEALTH_PORT}`);
    const runBase = /^ {6}base: (?<base>.*)$/mu.exec(template.slice(runStart))?.groups?.base;
    if (runBase === undefined) {
      return yield* Effect.fail(failure(`Missing run base for ${templateId}`));
    }
    return [
      buildAndDeploy,
      '    run:',
      `      base: ${runBase}`,
      '      ports:',
      `        - port: ${OUTBOX_WORKER_HOST_HEALTH_PORT}`,
      '          protocol: tcp',
      '          httpSupport: true',
      '      envVariables:',
      ...Arr.sort([...environment.keys()], Order.String).map((key) => `        ${key}: ${environment.get(key) ?? ''}`),
      '      healthCheck:',
      '        httpGet:',
      `          port: ${OUTBOX_WORKER_HOST_HEALTH_PORT}`,
      "          path: '/ready'",
      `      start: sh -c '${[...preflights].join('')}cd ${runtimeDir} && PATH="$PWD/node/bin:$PATH" exec npm run serve'`,
    ].join('\n');
  });

/**
 * @param {string} root Workspace root.
 * @param {string} source Existing Zerops deployment source.
 */
const generateOutboxWorkerDeploymentEffect = (root, source) =>
  Effect.gen(function* generateDeployment() {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const topologySource = yield* fs.readFileString(path.join(root, 'topology/reference-topology.json'));
    const topology = yield* Schema.decodeUnknownEffect(TopologySchema)(topologySource);
    let result = source.replace(
      /\n {2}# <generated-outbox-worker-deployments>[\s\S]*? {2}# <\/generated-outbox-worker-deployments>\n?/u,
      '\n',
    );
    /** @type {string[]} */
    const services = [];
    /** @type {string[]} */
    const serviceIds = [];
    for (const vertical of topology.verticals) {
      const delivery = yield* outboxWorkerDelivery(root, vertical).pipe(
        Effect.mapError(() => failure(`Invalid generated worker delivery for ${vertical.id}`)),
      );
      if (delivery === undefined) {
        continue;
      }
      const ownerSection = result
        .split(/(?=^ {2}(?:- setup:|# <\/generated-vertical-provider-deployments>))/mu)
        .find((section) => section.startsWith(`  - setup: '${vertical.id}'\n`));
      if (ownerSection === undefined) {
        return yield* Effect.fail(failure(`Missing owner deployment for ${vertical.id}`));
      }
      const port = /^ {8}PORT: '(?<port>[0-9]+)'$/mu.exec(ownerSection)?.groups?.port;
      const topologyPort = yield* Effect.try({
        catch: () => failure(`Invalid topology manifest URL for ${vertical.id}`),
        try: () => new URL(vertical.moduleFederation.manifestUrl).port,
      });
      if (port === undefined || port.length === 0 || port !== topologyPort) {
        return yield* Effect.fail(failure(`Owner port disagrees with topology for ${vertical.id}`));
      }
      // The worker keeps its owner's generated PostgreSQL binding. Referencing the owner's variable instead
      // (`${owner}_DATABASE_URL`) reaches the worker unresolved: Zerops does not expand the `${db18_*}`
      // references nested inside another service's variable, so the worker exited on a malformed URL.
      const service = ownerSection
        .trimEnd()
        .replace(`setup: '${vertical.id}'`, `setup: '${delivery.id}'`)
        .replaceAll(`runtime/${vertical.id}`, `runtime/${delivery.id}`)
        .split('\n')
        .filter(
          (line) =>
            !line.includes(' run build') && !line.includes("- cp 'app/topology/") && !line.includes('VERTICAL_'),
        )
        .map((line) =>
          line.includes('run zerops:materialize')
            ? line.replace('cd app && ', 'cd app && ULTRAMODERN_SOURCE_REVISION="$(git rev-parse HEAD)" ')
            : line,
        )
        .join('\n')
        .replace(/(?<command>run zerops:materialize[^\n]*)/u, '$<command> --worker')
        .replaceAll(`/${vertical.id}-api/${vertical.id}/readiness`, '/ready')
        .replace(`ULTRAMODERN_ZEROPS_SERVICE: ${vertical.id}`, `ULTRAMODERN_ZEROPS_SERVICE: ${delivery.id}`)
        .replace(`        PORT: '${port}'`, `        PORT: '${port}'\n        OUTBOX_WORKER_HEALTH_PORT: '${port}'`);
      services.push(service);
      serviceIds.push(delivery.id);
    }
    const host = yield* readOutboxWorkerHost(root);
    if (host === undefined) {
      return { deployment: result, hostEntry: null };
    }
    const rootPackage = yield* Schema.decodeUnknownEffect(RootPackageSchema)(
      yield* fs.readFileString(path.join(root, 'package.json')),
    );
    // The Zerops target deploys each owner's dedicated worker; the Cloudflare target deploys the host instead.
    const hostService = yield* renderHostService(services, serviceIds, rootPackage.name);
    result = `${result.trimEnd()}\n\n  # <generated-outbox-worker-deployments>\n${[...services, hostService].join('\n\n')}\n  # </generated-outbox-worker-deployments>\n`;
    return { deployment: result, hostEntry: renderOutboxWorkerHostEntry(host) };
  });

/**
 * @param {string} root Workspace root.
 * @param {string} source Existing Zerops deployment source.
 * @returns {PromiseLike<{ deployment: string, hostEntry: string | null }>} Deployment source with the generated worker services, and the Outbox Worker host entry source.
 */
export const generateOutboxWorkerDeployment = (root, source) =>
  nodeRuntime.runPromise(generateOutboxWorkerDeploymentEffect(root, source));

/** @param {{ write: boolean }} options Parsed command options. */
const runCommand = ({ write }) =>
  Effect.gen(function* runDeploymentGenerator() {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const root = path.resolve();
    const file = path.join(root, 'zerops.yaml');
    const hostEntryFile = path.join(root, OUTBOX_WORKER_HOST.entry);
    const source = yield* fs.readFileString(file);
    const currentHostEntry = (yield* fs.exists(hostEntryFile)) ? yield* fs.readFileString(hostEntryFile) : null;
    const generated = yield* generateOutboxWorkerDeploymentEffect(root, source);
    if (write) {
      yield* fs.writeFileString(file, generated.deployment);
      yield* generated.hostEntry === null
        ? fs.remove(hostEntryFile, { force: true })
        : fs.writeFileString(hostEntryFile, generated.hostEntry);
    } else if (source !== generated.deployment || currentHostEntry !== generated.hostEntry) {
      yield* Effect.fail(
        failure('Worker deployment drift: run node scripts/generate-outbox-worker-deployment.mjs --write'),
      );
    }
  });

const command = Command.make(
  'generate-outbox-worker-deployment',
  { write: Flag.Boolean('write').pipe(Flag.withDefault(false)) },
  runCommand,
);

if (import.meta.main) {
  void nodeRuntime.runPromise(Command.run(command, { version: '1.0.0' }));
}
