import fs from 'node:fs';
import path from 'node:path';

/** A generated worker host is the deployment capability; topology owns its identity. */
export const outboxWorkerDelivery = (root, vertical) => {
  const packagePath = path.join(root, vertical.path, 'package.json');
  if (!fs.existsSync(packagePath)) {
    return;
  }
  const ownerPackage = JSON.parse(fs.readFileSync(packagePath, 'utf-8'));
  if (!ownerPackage.scripts?.['worker:start']) {
    return;
  }
  const entry = 'src/worker-host/main.ts';
  const host = fs.readFileSync(path.join(root, vertical.path, entry), 'utf-8');
  if (
    ownerPackage.name !== vertical.package ||
    ownerPackage.scripts['worker:start'] !== `node --experimental-strip-types ./${entry}` ||
    !host.startsWith('// @generated by scaffold:outbox-worker worker-host\n')
  ) {
    throw new Error(`Invalid generated worker delivery for ${vertical.id}`);
  }
  return {
    entry,
    id: `${vertical.id}-worker`,
    ownerId: vertical.id,
    packageName: vertical.package,
    path: vertical.path,
    serviceIdEnv: `ZEROPS_${vertical.id.replaceAll('-', '_').toUpperCase()}_WORKER_SERVICE_ID`,
    stageSetup: `${vertical.id}-worker`,
  };
};
