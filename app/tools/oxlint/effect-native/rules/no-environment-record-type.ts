/**
 * effect-native/no-environment-record-type
 *
 * Audit findings enforced (docs/architecture/EFFECT_V4_ANTIPATTERN_AUDIT.md):
 *   - A3 "Replace ambient configuration with Config, ConfigProvider, and Redacted" —
 *     `type Environment = Readonly<Record<string, string | undefined>>` is repeated across
 *     `packages/core-runtime/src/db/config.ts`, `packages/core-runtime/src/permissions/config.ts`,
 *     `packages/core-runtime/src/outbox/poller.ts`, `apps/shell-super-app/api/auth/config.ts`,
 *     `apps/shell-super-app/api/auth/gateway-issuer-config.ts`,
 *     `verticals/contacts/api/auth/action-principal.ts` and friends. Every one of them makes an
 *     untyped string dictionary the configuration authority: nothing declares which keys exist,
 *     nothing decodes them, nothing marks the secret ones, and the requirement never reaches the
 *     Layer graph. The audit target is "create one application configuration Schema … decode it
 *     through `Config`, `Config.schema`, and a root `ConfigProvider` … represent key material and
 *     credentials using `Redacted`".
 *   - A2 "Make Schema the sole authority for contracts and domain models" —
 *     "hundreds of overlapping hand-authored shapes"; a `Record<string, string | undefined>` is the
 *     most degenerate of them. It admits every key, decodes nothing, and forces each reader to
 *     re-derive `undefined` handling by hand (`environment['ONTOS_GATEWAY_ISSUER']` +
 *     `if (issuer === undefined) throw …`).
 *
 * ## What is detected
 *
 *   1. `environmentRecord` — a `Record<string, …>` / `ReadonlyRecord<string, …>` /
 *      `Record.ReadonlyRecord<string, …>` type reference whose **key** is the `string` keyword and
 *      whose **value** is a union built only from `string`, `undefined` and `null` that contains
 *      `string` plus at least one of `undefined` / `null`. `Readonly<…>` / `Partial<…>` wrappers do
 *      not rescue it, and neither does parenthesising the members. The `Record` node itself is
 *      reported, so a wrapper never produces a second diagnostic.
 *   2. `environmentRecord` (partial form) — `Partial<Record<string, string>>`, which *is*
 *      `Record<string, string | undefined>` spelled differently. Only a `string` key qualifies:
 *      `Readonly<Partial<Record<'id' | 'contactId', string>>>` (the route-param maps generated by
 *      `scripts/scaffolding/microvertical-page`) has a closed literal key set and is left alone.
 *   3. `environmentIndexSignature` — the inline spelling
 *      `{ [key: string]: string | undefined }` / `{ readonly [name: string]: string | null }`, in a
 *      type literal or an interface body. Recursive JSON shapes such as
 *      `type LocaleResource = string | { readonly [key: string]: LocaleResource }` do not match:
 *      their value type is not a string/undefined/null union.
 *   4. `processEnvType` — the ambient environment used *as a type*: `NodeJS.ProcessEnv`,
 *      `NodeJS.Dict<string>`, `typeof process.env` / `typeof globalThis.process.env` /
 *      `typeof Bun.env` / `typeof Deno.env` (`TSTypeQuery`), and
 *      `import("node:process").ProcessEnv` (`TSImportType`). `effect-native/no-ambient-process-env`
 *      deliberately allows type positions; this rule is the half that closes them.
 *
 * Each site is reported exactly once, on the offending type node. Alias *references* are never
 * re-reported: `type Environment = Readonly<Record<string, string | undefined>>` reports once at the
 * declaration, and the twelve `environment: Environment` parameters that follow stay silent — the
 * alias is a `TSTypeReference` to `Environment`, not to `Record`.
 *
 * ## What is deliberately allowed
 *
 *   - `Record<string, string>` and `Readonly<Record<string, string>>` — a total map (HTTP headers,
 *     log annotations, i18n resources, `scripts/local-environment-values.mts`). The defect this rule
 *     names is the *optional* dictionary standing in for a decoded configuration Struct.
 *   - `Record<string, unknown>` / `Record<string, JsonValue>` — JSON normalisation shapes. The audit
 *     blesses `Schema.Json`-backed payloads and "`Array.isArray` in recursive JSON normalization";
 *     an `unknown`-valued map is not an environment dictionary.
 *   - Closed literal key sets: `Partial<Record<'id', string>>`, `Record<ModuleId, string>`,
 *     `Partial<Record<keyof CustomerFormValues, string>>`.
 *   - Closed-key mapped types (`{ [K in Keys]?: string }`), `Map`/`ReadonlyMap`, and every generic parameter
 *     shape — this rule is purely about the string-keyed optional dictionary spelling.
 *   - Tests, by default (`ignoreTestFiles: true`): fixture builders legitimately assemble loose
 *     string maps, and audit B2's target for tests is `ConfigProvider.fromMap`, which is enforced by
 *     `effect-native/no-ambient-process-env` instead.
 *   - Anything under `allowPaths` (empty by default — no carve-out has been ratified).
 *
 * Scope lives in the rule (`includePaths` defaults to `apps/**`, `verticals/**`, `packages/**`,
 * `scripts/**`), so `oxlint.config.ts` only needs
 * `'effect-native/no-environment-record-type': 'error'`.
 *
 * Closed NodeJS.ProcessEnv declaration augmentations are not themselves open dictionary use sites.
 * Scope/import-aware but syntax-only: external aliases and semantic key/value equivalences are not inferred.
 * Report-only: no fixers, no suggestions.
 */
import { defineRule } from '@oxlint/plugins';

import type { ESTree, Scope } from '@oxlint/plugins';

import { collectEffectBindings } from '../shared/effect-imports.ts';
import { isTestFile, matchesAny, normalisePath } from '../shared/paths.ts';

type AnyNode = ESTree.Node;

/** Normalize real paths and remove only the fixture prefix, preserving nested workspace directories. */
function workspacePath(filename: string): string {
  return normalisePath(filename).replace(
    /^tools\/oxlint\/[^/]+\/tests\/fixtures\/[^/]+\/(?:valid|invalid)\//u,
    '',
  );
}

const DEFAULT_INCLUDE_PATHS: readonly string[] = [
  'apps/**',
  'verticals/**',
  'packages/**',
  'scripts/**',
];

/** Type constructors that spell "string-keyed dictionary". */
const RECORD_NAMES = new Set(['Record', 'ReadonlyRecord', 'Record.ReadonlyRecord']);

/** Wrappers that leave the underlying dictionary shape intact. */
const TRANSPARENT_WRAPPERS = new Set(['Readonly', 'Partial', 'Required']);

/** Globals that can host an `env` bag inside a `typeof` type query. */
const ENV_HOSTS = new Set(['process', 'Bun', 'Deno']);

/** Globals used to reach an env host indirectly (`typeof globalThis.process.env`). */
const CONTAINER_GLOBALS = new Set(['globalThis', 'global', 'window', 'self']);

/** Ambient node typings that *are* the environment dictionary. */
const NODEJS_ENV_TYPES = new Set(['NodeJS.ProcessEnv', 'NodeJS.Dict']);

const PROCESS_MODULES = new Set(['process', 'node:process']);

interface RuleOptions {
  readonly allowPaths: readonly string[];
  readonly ignoreTestFiles: boolean;
  readonly includePaths: readonly string[];
}

const DEFAULTS: RuleOptions = {
  allowPaths: [],
  ignoreTestFiles: true,
  includePaths: [...DEFAULT_INCLUDE_PATHS],
};

function stringList(value: unknown, fallback: readonly string[]): readonly string[] {
  return Array.isArray(value) && value.every((entry) => typeof entry === 'string')
    ? (value as readonly string[])
    : fallback;
}

function readOptions(raw: unknown): RuleOptions {
  const given = (raw ?? {}) as Partial<Record<keyof RuleOptions, unknown>>;
  const includePaths = stringList(given.includePaths, DEFAULTS.includePaths);
  return {
    allowPaths: stringList(given.allowPaths, DEFAULTS.allowPaths),
    ignoreTestFiles:
      typeof given.ignoreTestFiles === 'boolean' ? given.ignoreTestFiles : DEFAULTS.ignoreTestFiles,
    includePaths: includePaths.length > 0 ? includePaths : DEFAULTS.includePaths,
  };
}

function parentOf(node: AnyNode): AnyNode | null {
  return (node as { parent?: AnyNode | null }).parent ?? null;
}

/** `(A | B)` → `A | B`; every other node is returned unchanged. */
function unwrapParens(node: AnyNode): AnyNode {
  let current = node;
  while (current.type === 'TSParenthesizedType') {
    current = (current as ESTree.TSParenthesizedType).typeAnnotation as AnyNode;
  }
  return current;
}

/** `Record` → `"Record"`, `Record.ReadonlyRecord` → `"Record.ReadonlyRecord"`, `this` → `null`. */
function dottedTypeName(node: AnyNode | null): string | null {
  if (node === null) return null;
  if (node.type === 'Identifier') return (node as { name: string }).name;
  if (node.type === 'MemberExpression' && !node.computed) {
    const left = dottedTypeName(node.object as AnyNode);
    return left === null ? null : `${left}.${(node.property as { name: string }).name}`;
  }
  if (node.type === 'TSQualifiedName') {
    const qualified = node as ESTree.TSQualifiedName;
    const left = dottedTypeName(qualified.left as AnyNode);
    return left === null ? null : `${left}.${qualified.right.name}`;
  }
  return null;
}

function typeReferenceName(node: AnyNode): string | null {
  return dottedTypeName(
    (node as { typeName?: AnyNode; expression?: AnyNode }).typeName ??
      (node as { expression?: AnyNode }).expression ??
      null,
  );
}

function typeArgumentsOf(node: AnyNode): readonly AnyNode[] {
  const params = (node as { typeArguments?: { params?: readonly AnyNode[] } | null }).typeArguments;
  return params?.params ?? [];
}

/**
 * `true` for a union built only from `string`, `undefined` and `null` that contains `string` plus at
 * least one absence member — the exact shape of an environment bag value.
 */
function isOptionalStringUnion(node: AnyNode): boolean {
  const type = unwrapParens(node);
  if (type.type !== 'TSUnionType') return false;
  let hasString = false;
  let hasAbsence = false;
  const pending: AnyNode[] = [...((type as ESTree.TSUnionType).types as readonly AnyNode[])];
  for (let guard = 0; pending.length > 0 && guard < 64; guard += 1) {
    const member = unwrapParens(pending.pop() as AnyNode);
    if (member.type === 'TSUnionType') {
      pending.push(...((member as ESTree.TSUnionType).types as readonly AnyNode[]));
      continue;
    }
    if (member.type === 'TSStringKeyword') hasString = true;
    else if (member.type === 'TSUndefinedKeyword' || member.type === 'TSNullKeyword')
      hasAbsence = true;
    else return false;
  }
  return pending.length === 0 && hasString && hasAbsence;
}

/** `true` when the node is somewhere inside a `Partial<…>` reached only through wrapper types. */
function isInsidePartial(node: AnyNode): boolean {
  let current = node;
  while (true) {
    const parent = parentOf(current);
    if (parent === null) return false;
    // A type argument's parent is the instantiation list, not the reference that owns it.
    if (parent.type === 'TSParenthesizedType' || parent.type === 'TSTypeParameterInstantiation') {
      current = parent;
      continue;
    }
    if (!['TSTypeReference', 'TSInterfaceHeritage', 'TSClassImplements'].includes(parent.type))
      return false;
    const name = typeReferenceName(parent);
    if (name === null || !TRANSPARENT_WRAPPERS.has(name)) return false;
    if (name === 'Partial') return true;
    current = parent;
  }
  return false;
}

/**
 * `typeof process.env` / `typeof globalThis.process.env` / `typeof Deno.env` → `true`.
 * The chain is flattened, leading container globals are stripped, and the remainder must be
 * `<env host>.env`.
 */
function isAmbientEnvQueryName(node: AnyNode): boolean {
  const dotted = dottedTypeName(node);
  if (dotted === null) return false;
  const segments = dotted.split('.');
  while (segments.length > 2 && CONTAINER_GLOBALS.has(segments[0] ?? '')) segments.shift();
  if (segments.length !== 2) return false;
  return ENV_HOSTS.has(segments[0] ?? '') && segments[1] === 'env';
}

/** Effect-native rule: configuration is a Schema decoded through Config and injected as a service. */
export const rule = defineRule({
  meta: {
    type: 'problem',
    docs: {
      description:
        'Audit A3/A2: `Record<string, string | undefined>`, `{ [key: string]: string | undefined }` and `NodeJS.ProcessEnv` / `typeof process.env` make an untyped environment dictionary the configuration authority instead of one Schema decoded through Config/ConfigProvider and injected as a Context.Service.',
      url: 'docs/architecture/EFFECT_V4_ANTIPATTERN_AUDIT.md#a3-replace-ambient-configuration-with-config-configprovider-and-redacted',
    },
    messages: {
      openDictionary:
        'Audit A3/A2: `{{type}}` is an open optional string dictionary. For configuration, declare settings through Schema/Config and inject the decoded service; for decoded HttpApi headers, route parameters or persistence rows, preserve the owning Schema-derived contract instead of widening it to this map. This syntactic rule cannot infer the map’s domain.',
      environmentRecord:
        'Audit A3/A2: `{{type}}` models configuration as an untyped environment dictionary — no key is declared, nothing is decoded, no value can be `Redacted`, and every reader re-derives its own `undefined` handling. Declare the settings once as a `Schema.Struct` (with `Schema.Redacted` for credentials and key material), decode it with `Config.schema`/`Config.all`, provide it from the single root `ConfigProvider`, and inject the decoded value as a `Context.Service` instead of threading a string map through the call graph.',
      environmentIndexSignature:
        'Audit A3/A2: the index signature `{{type}}` is an open string-keyed dictionary standing in for a declared configuration shape, so no key is validated and no value can be `Redacted`. Replace it with a `Schema.Struct` of the fields this code actually needs, decode it through `Config.schema`/`Config.all` under the root `ConfigProvider`, and inject the result as a `Context.Service`.',
      processEnvType:
        'Audit A3: `{{type}}` makes the ambient process environment the configuration type, so the requirement never appears in the Layer graph and cannot be substituted in a test. Type the settings as a `Schema.Struct`, decode it with `Config.schema` under one root `ConfigProvider` (`ConfigProvider.fromMap` in tests), and inject the decoded configuration as a `Context.Service`.',
    },
    schema: [
      {
        type: 'object',
        additionalProperties: false,
        properties: {
          allowPaths: {
            type: 'array',
            items: { type: 'string' },
            description:
              'Globs of files allowed to declare string-keyed environment dictionaries (default: none — no carve-out has been ratified).',
          },
          ignoreTestFiles: {
            type: 'boolean',
            description:
              'Skip test files (default: true — test fixtures legitimately assemble loose string maps; ambient test configuration is covered by effect-native/no-ambient-process-env).',
          },
          includePaths: {
            type: 'array',
            items: { type: 'string' },
            description:
              'Globs the rule applies to (default: apps/**, verticals/**, packages/**, scripts/**).',
          },
        },
      },
    ],
    defaultOptions: [
      { allowPaths: [], ignoreTestFiles: true, includePaths: [...DEFAULT_INCLUDE_PATHS] },
    ],
  },
  create(context) {
    const options = readOptions(context.options[0]);
    const path = workspacePath(context.filename);
    if (!matchesAny(`/${path}`, options.includePaths)) return {};
    if (matchesAny(`/${path}`, options.allowPaths)) return {};
    if (options.ignoreTestFiles && isTestFile(`/${path}`)) return {};

    const printed = (node: AnyNode): string => {
      const text = context.sourceCode.getText(node).replace(/\s+/gu, ' ').trim();
      return text.length > 80 ? `${text.slice(0, 77)}...` : text;
    };

    const report = (node: AnyNode, messageId: string): void => {
      context.report({
        node,
        messageId: messageId === 'processEnvType' ? messageId : 'openDictionary',
        data: { type: printed(node) },
      });
    };

    const bindings = collectEffectBindings(context.sourceCode.ast);
    const lookup = (name: string, node: AnyNode) => {
      for (
        let scope: Scope | null = context.sourceCode.getScope(node);
        scope;
        scope = scope.upper
      ) {
        const variable = scope.set.get(name);
        if (variable) return variable;
      }
      return null;
    };
    // Import identity, not the local spelling, distinguishes Effect.Record from domain lookalikes.
    const canonicalName = (node: AnyNode): string | null => {
      const name = typeReferenceName(node);
      if (!name) return null;
      const [root, ...rest] = name.split('.');
      const variable = lookup(root, node);
      if (!variable || variable.defs.length === 0) return name;
      const definition = variable.defs.length === 1 ? variable.defs[0] : undefined;
      if (definition?.type !== 'ImportBinding') return null;
      const specifier = definition.node as ESTree.ImportDeclaration['specifiers'][number];
      const declaration = parentOf(specifier as AnyNode) as ESTree.ImportDeclaration;
      if (!declaration || !['effect', 'effect/Record'].includes(declaration.source.value))
        return null;
      const imported = bindings.namespaces.get(root);
      if (
        declaration.source.value === 'effect/Record' &&
        specifier.type === 'ImportSpecifier' &&
        imported === 'ReadonlyRecord' &&
        rest.length === 0
      )
        return 'ReadonlyRecord';
      return imported === 'Record' && rest.join('.') === 'ReadonlyRecord'
        ? 'Record.ReadonlyRecord'
        : null;
    };
    const isAmbientQuery = (expression: AnyNode, indexed = false): boolean => {
      const name = dottedTypeName(expression);
      if (!name) return false;
      const full = indexed ? `${name}.env` : name;
      const segments = full.split('.');
      const root = segments[0];
      const variable = lookup(root, expression);
      if (variable && variable.defs.length > 0) {
        const definition = variable.defs.length === 1 ? variable.defs[0] : undefined;
        if (definition?.type !== 'ImportBinding') return false;
        const specifier = definition.node as ESTree.ImportDeclaration['specifiers'][number];
        const declaration = parentOf(specifier as AnyNode) as ESTree.ImportDeclaration;
        return (
          declaration?.type === 'ImportDeclaration' &&
          PROCESS_MODULES.has(declaration.source.value) &&
          segments.length === 2 &&
          segments[1] === 'env' &&
          (specifier.type === 'ImportDefaultSpecifier' ||
            specifier.type === 'ImportNamespaceSpecifier')
        );
      }
      return (
        (segments.length === 2 && ENV_HOSTS.has(root) && segments[1] === 'env') ||
        (segments.length === 3 &&
          CONTAINER_GLOBALS.has(root) &&
          ENV_HOSTS.has(segments[1]) &&
          segments[2] === 'env')
      );
    };
    const inspectReference = (node: AnyNode): void => {
      // A generic utility constraint is not a declaration of configuration authority.
      let ancestor = parentOf(node);
      while (ancestor && ancestor.type !== 'Program') {
        if (
          ancestor.type === 'TSTypeParameter' &&
          ancestor.constraint &&
          node.start >= ancestor.constraint.start &&
          node.end <= ancestor.constraint.end
        )
          return;
        ancestor = parentOf(ancestor);
      }
      const name = canonicalName(node);
      if (name === null) return;

      if (NODEJS_ENV_TYPES.has(name)) {
        // `NodeJS.Dict<T>` is only the environment shape when `T` is `string`.
        if (name === 'NodeJS.Dict') {
          const argument = typeArgumentsOf(node as unknown as AnyNode)[0];
          if (
            argument === undefined ||
            (unwrapParens(argument).type !== 'TSStringKeyword' && !isOptionalStringUnion(argument))
          )
            return;
        }
        report(node as unknown as AnyNode, 'processEnvType');
        return;
      }

      if (!RECORD_NAMES.has(name)) return;
      const args = typeArgumentsOf(node as unknown as AnyNode);
      if (args.length !== 2) return;
      const key = unwrapParens(args[0] as AnyNode);
      if (key.type !== 'TSStringKeyword') return;
      const value = args[1] as AnyNode;
      if (isOptionalStringUnion(value)) {
        report(node as unknown as AnyNode, 'environmentRecord');
        return;
      }
      // `Partial<Record<string, string>>` *is* `Record<string, string | undefined>`.
      if (
        unwrapParens(value).type === 'TSStringKeyword' &&
        isInsidePartial(node as unknown as AnyNode)
      ) {
        report(node as unknown as AnyNode, 'environmentRecord');
      }
    };
    return {
      TSTypeReference: inspectReference,
      TSInterfaceHeritage: inspectReference,
      TSClassImplements: inspectReference,
      TSMappedType(node) {
        const constraint = node.constraint;
        const value = node.typeAnnotation;
        if (
          !constraint ||
          unwrapParens(constraint).type !== 'TSStringKeyword' ||
          !value ||
          node.nameType
        )
          return;
        if (
          isOptionalStringUnion(value) ||
          ((node.optional === true || node.optional === '+') &&
            unwrapParens(value).type === 'TSStringKeyword')
        )
          report(node, 'environmentIndexSignature');
      },
      TSIndexedAccessType(node) {
        const object = unwrapParens(node.objectType);
        const index = unwrapParens(node.indexType);
        if (
          object.type === 'TSTypeQuery' &&
          index.type === 'TSLiteralType' &&
          index.literal.type === 'Literal' &&
          index.literal.value === 'env' &&
          isAmbientQuery(object.exprName, true)
        )
          report(node, 'processEnvType');
      },

      // `{ [key: string]: string | undefined }` and the `interface` spelling of it.
      TSIndexSignature(node) {
        const parameter = (node.parameters as readonly AnyNode[])[0];
        if (parameter === undefined) return;
        const keyType = (parameter as { typeAnnotation?: { typeAnnotation?: AnyNode } })
          .typeAnnotation?.typeAnnotation;
        if (keyType === undefined || unwrapParens(keyType).type !== 'TSStringKeyword') return;
        const valueType = (node.typeAnnotation as { typeAnnotation?: AnyNode } | null)
          ?.typeAnnotation;
        if (valueType === undefined || valueType === null) return;
        if (!isOptionalStringUnion(valueType)) return;
        report(node as unknown as AnyNode, 'environmentIndexSignature');
      },

      // `typeof process.env`, `typeof globalThis.process.env`, `typeof Deno.env`.
      TSTypeQuery(node) {
        const exprName = node.exprName as AnyNode;
        if (!isAmbientQuery(exprName)) return;
        report(node as unknown as AnyNode, 'processEnvType');
      },

      // `import("node:process").ProcessEnv`.
      TSImportType(node) {
        if (!PROCESS_MODULES.has(node.source.value)) return;
        const qualifier = node.qualifier as AnyNode | null;
        const dotted = qualifier === null ? null : dottedTypeName(qualifier);
        if (dotted !== 'ProcessEnv' && dotted !== 'env') return;
        report(node as unknown as AnyNode, 'processEnvType');
      },
    };
  },
});
