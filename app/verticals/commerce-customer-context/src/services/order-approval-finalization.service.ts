export const verifyOrderFinalizationSnapshot = (
  before: OrderFinalizationSnapshot,
  current: OrderFinalizationSnapshot,
  validUntil: number,
  now: number,
): Effect.Effect<void, PurchasingApprovalRejected> =>
  sameOrderSnapshot(before, current) && Number.isFinite(validUntil) && now < validUntil
    ? Effect.void
    : Effect.fail(unavailable('The retained Order approval state changed or its prepared evidence expired'));

export const finishOrderFinalizationRead = Effect.fn('OrderApprovalFinalization.finishRead')(function* finishRead(
  input: OrderServiceApprovalEvidenceRequest,
  context: ReadFinishContext<
    Effect.Success<ReturnType<typeof prepareOrderFinalizationRead>>,
    Effect.Success<ReturnType<typeof loadOrderFinalizationReadSnapshot>>
  >,
) {
  const { loaded, prepared, scope } = context;
  const { request } = loaded.snapshot;
  const deadline = DateTime.toEpochMillis(prepared.observedAt) + MAX_EVIDENCE_WINDOW_MS;
  const remote = yield* orderApprovalFinalizationRemote(scope, prepared.revision);
  if (context.compositionRevision !== undefined && context.compositionRevision !== prepared.revision) {
    return yield* unavailable('The prepared Order read belongs to another composition');
  }
  if (input.operation === 'LOAD_APPROVED_IDENTITY') {
    if (loaded.kind !== 'PRICING') {
      return yield* unavailable('The prepared pricing snapshot is absent');
    }
    const observation = yield* resolvePurchasePricingContextFromSnapshot(
      scope,
      request,
      prepared.revision,
      DateTime.formatIso(input.operationTime),
      loaded.pricing,
    ).pipe(Effect.mapError(unavailable));
    yield* context.transaction(
      Effect.fn('OrderApprovalFinalization.recheckPricing')(function* recheckPricing(
        transaction: ScopedTransactionExecutor,
      ) {
        const current = yield* loadOrderFinalizationReadSnapshot(transaction, scope, input);
        yield* verifyOrderFinalizationSnapshot(
          loaded.snapshot,
          current.snapshot,
          Math.min(deadline, observation.validUntil),
          DateTime.toEpochMillis(yield* DateTime.now),
        );
        if (current.kind !== 'PRICING' || stableRevision(current.pricing) !== stableRevision(loaded.pricing)) {
          return yield* unavailable('The Order pricing owner state changed during remote resolution');
        }
        return yield* Effect.void;
      }),
    );
    const { proposal } = request;
    return yield* Schema.decodeUnknownEffect(Schema.toType(OrderServiceApprovalEvidenceResponseSchema))({
      buyerPrincipalId: proposal.identity.buyer.principalId,
      cartRef: proposal.sourceCart.cartRef,
      cartRevision: proposal.sourceCart.revision,
      counterpartyRef: proposal.identity.counterpartyRef,
      legalEntityId: scope.legalEntityId,
      operation: input.operation,
      pricingContext: observation.context,
      proposal,
      proposalHash: proposal.canonicalHash,
      proposalRevisionRef: proposal.proposalRevisionRef,
      requestRef: request.requestRef,
      storefrontId: proposal.context.storefrontId,
      tenantId: scope.tenantId,
    }).pipe(Effect.mapError(unavailable));
  }
  const candidate = yield* remote.loadCandidate(input, request);
  const candidateIdentity = { candidateHash: candidate.candidateHash, candidateRef: candidate.candidateRef };
  if (input.operation === 'RESOLVE_PAYMENT_TERMS') {
    const payment = yield* context.transaction(
      Effect.fn('OrderApprovalFinalization.loadPayment')(function* loadPayment(transaction: ScopedTransactionExecutor) {
        const current = yield* loadOrderApprovalFinalizationSnapshot(transaction, scope, input.requestRef, false);
        yield* verifyOrderFinalizationSnapshot(
          loaded.snapshot,
          current,
          deadline,
          DateTime.toEpochMillis(yield* DateTime.now),
        );
        return yield* loadOrderFinalizationPaymentTermsSnapshot(transaction, scope, request, candidate).pipe(
          Effect.mapError(unavailable),
        );
      }),
    );
    const resolution = yield* finishOrderFinalizationPaymentTerms(scope, request, payment, prepared.revision).pipe(
      Effect.mapError(unavailable),
    );
    yield* context.transaction(
      Effect.fn('OrderApprovalFinalization.recheckPayment')(function* recheckPayment(
        transaction: ScopedTransactionExecutor,
      ) {
        const current = yield* loadOrderApprovalFinalizationSnapshot(transaction, scope, input.requestRef, false);
        yield* verifyOrderFinalizationSnapshot(
          loaded.snapshot,
          current,
          deadline,
          DateTime.toEpochMillis(yield* DateTime.now),
        );
        const latest = yield* loadOrderFinalizationPaymentTermsSnapshot(transaction, scope, request, candidate).pipe(
          Effect.mapError(unavailable),
        );
        if (stableRevision(latest) !== stableRevision(payment)) {
          return yield* unavailable('The Order Payment Terms owner state changed during remote resolution');
        }
        return yield* Effect.void;
      }),
    );
    return yield* Schema.decodeUnknownEffect(Schema.toType(OrderServiceApprovalEvidenceResponseSchema))({
      operation: input.operation,
      ...candidateIdentity,
      resolution,
    }).pipe(Effect.mapError(unavailable));
  }
  const result = yield* context.transaction(
    Effect.fn('OrderApprovalFinalization.finishLocalProofRead')(function* finishLocalProofRead(
      transaction: ScopedTransactionExecutor,
    ) {
      const current = yield* loadOrderApprovalFinalizationSnapshot(
        transaction,
        scope,
        input.requestRef,
        input.operation === 'RECOVER_REVALIDATION',
      );
      yield* verifyOrderFinalizationSnapshot(
        loaded.snapshot,
        current,
        deadline,
        DateTime.toEpochMillis(yield* DateTime.now),
      );
      if (input.operation === 'LOAD_PROPOSAL') {
        return { operation: input.operation, ...candidateIdentity, proposal: request.proposal, request };
      }
      const services = yield* orderApprovalFinalizationService(transaction, scope);
      return yield* input.operation === 'RECOVER_REVALIDATION'
        ? services.recoverRevalidation(input, request, candidate)
        : services.verifyRetainedProof(input, request, candidate);
    }),
  );
  return yield* Schema.decodeUnknownEffect(Schema.toType(OrderServiceApprovalEvidenceResponseSchema))(result).pipe(
    Effect.mapError(unavailable),
  );
});

export const preparedOrderCurrentness = ({
  bundlePurchaseValue,
  facts,
  observedAt,
  request,
  scope,
  validUntil,
}: {
  readonly bundlePurchaseValue: typeof PurchaseValueSchema.Type;
  readonly facts: typeof PurchaseLimitEvaluationCurrentFactsSchema.Type;
  readonly observedAt: DateTime.Utc;
  readonly request: OrderRequestSnapshot;
  readonly scope: OperationalScope;
  readonly validUntil: number;
}): PurchaseLimitEvaluationCurrentnessPortService => {
  const { proposal } = request;
  const currentness: PurchaseLimitEvaluationCurrentnessPortService = {
    resolveCurrent: Effect.fn('OrderApprovalFinalization.preparedCurrentness')(function* preparedCurrentness(input) {
      const nativeNow = yield* DateTime.now;
      if (
        DateTime.toEpochMillis(nativeNow) >= validUntil ||
        DateTime.isGreaterThan(input.observedAt, nativeNow) ||
        DateTime.isLessThan(input.observedAt, observedAt) ||
        input.scope.tenantId !== scope.tenantId ||
        input.scope.legalEntityId !== scope.legalEntityId ||
        input.scope.principalId !== proposal.identity.buyer.principalId ||
        input.scope.storefrontId !== proposal.context.storefrontId ||
        !sameRef(input.counterpartyRef, proposal.identity.counterpartyRef) ||
        !Schema.toEquivalence(PurchaseValueSchema)(input.claimedPurchaseValue, bundlePurchaseValue)
      ) {
        return yield* Effect.fail(
          PurchaseLimitDependencyUnavailableSchema.make({
            code: 'purchase_limit_dependency_unavailable',
            dependency: 'ORDER_FINALIZATION_CURRENTNESS',
            reason: 'Prepared Order observations are expired or do not match this exact purchase',
          }),
        );
      }
      return facts;
    }),
  };
  return currentness;
};

/** Captures immutable remote inputs between short owner transactions, before Action mutation. */
export const prepareOrderApprovalFinalizationEvidence = Effect.fn('OrderApprovalFinalization.prepareActionEvidence')(
  function* prepareActionEvidence(
    payload: RevalidateOrderPurchaseApprovalPayload,
    context: ActionServicePreparationContext,
  ) {
    const { scope } = context;
    const remote = yield* orderApprovalFinalizationRemote(scope, context.compositionRevision);
    yield* remote.authorize('REVALIDATE');
    const revision = yield* remote.activeRevision();
    const operationTime = DateTime.formatIso(yield* DateTime.now);
    const before = yield* context.transaction(
      Effect.fn('OrderApprovalFinalization.snapshotAction')(function* snapshotAction(
        transaction: ScopedTransactionExecutor,
      ) {
        const snapshot = yield* loadOrderApprovalFinalizationSnapshot(transaction, scope, payload.requestRef, false);
        const pricing = yield* loadPurchasePricingContextSnapshot(
          transaction,
          scope,
          snapshot.request,
          operationTime,
        ).pipe(Effect.mapError(unavailable));
        return { pricing, snapshot };
      }),
    );
    const { snapshot } = before;
    const { request } = snapshot;
    const { proposal } = request;
    if (request.status !== 'APPROVED' || request.lastDecisionRef === null) {
      return yield* rejected();
    }
    const { candidate, credential } = yield* Effect.all(
      { candidate: remote.loadCandidate(payload, request), credential: remote.gateway('commerce-order') },
      { concurrency: 1 },
    );
    const query = yield* Schema.decodeUnknownEffect(Schema.toType(PreparedOrderApprovalBindingRequestSchema))({
      binding: payload.finalBinding,
      candidateHash: candidate.candidateHash,
      candidateRef: candidate.candidateRef,
      commitmentCorrelationId: payload.commitmentCorrelationId,
      proposalHash: proposal.canonicalHash,
      proposalRevisionRef: proposal.proposalRevisionRef,
      requestRef: request.requestRef,
    }).pipe(Effect.mapError(unavailable));
    const prepared = yield* executePreparedOrderApprovalBindingWithAuthorization(
      query,
      credential.authorization,
      scope.correlationId,
      { baseUrl: credential.configured.orderBaseUrl, compositionRevision: credential.revision },
    ).pipe(
      Effect.flatMap(Schema.decodeUnknownEffect(Schema.toType(PreparedOrderApprovalBindingResponseSchema))),
      Effect.mapError(unavailable),
    );
    const now = yield* DateTime.now;
    if (!preparedBindingAdmitted({ candidate, now, payload, prepared, request, scope })) {
      return yield* rejected();
    }
    const claimed = yield* Schema.decodeUnknownEffect(Schema.toType(RevalidatePurchaseApprovalInputSchema))({
      buyerPermission: 'ALLOWED',
      checkedAt: now,
      commitmentCorrelationId: payload.commitmentCorrelationId,
      counterpartyRef: proposal.identity.counterpartyRef,
      decisionBundleHash: request.decisionBundleHash,
      decisionBundleVersion: request.decisionBundleVersion,
      decisionRef: request.lastDecisionRef,
      expectedProposalHash: proposal.canonicalHash,
      finalBinding: payload.finalBinding,
      hierarchyRef: request.route.hierarchyRef,
      idempotencyKey: payload.idempotencyKey,
      profileState: 'ACTIVE',
      proposalRevisionRef: proposal.proposalRevisionRef,
      requestRef: request.requestRef,
      routeCurrent: true,
      routeRef: request.route.routeRef,
      sourceRevisions: snapshot.sourceRevisions,
      storefrontId: proposal.context.storefrontId,
      validUntil: DateTime.makeUnsafe(
        Math.min(
          DateTime.toEpochMillis(request.expiresAt),
          DateTime.toEpochMillis(proposal.expiresAt),
          DateTime.toEpochMillis(now) + 30_000,
          DateTime.toEpochMillis(prepared.validUntil),
        ),
      ),
    }).pipe(Effect.mapError(unavailable));
    const bundlePurchaseValue = yield* Schema.decodeUnknownEffect(Schema.toType(PurchaseValueSchema))(
      prepared.bundlePurchaseValue,
    ).pipe(Effect.mapError(unavailable));

    const observation = yield* resolvePurchasePricingContextFromSnapshot(
      scope,
      request,
      revision,
      operationTime,
      before.pricing,
    ).pipe(Effect.mapError(unavailable));
    const validUntil = Math.min(
      observation.validUntil,
      DateTime.toEpochMillis(claimed.validUntil),
      DateTime.toEpochMillis(prepared.validUntil),
    );
    const facts = yield* Schema.decodeUnknownEffect(PurchaseLimitEvaluationCurrentFactsSchema)({
      channelId: observation.context.commercialScope.channelId,
      contextRevision: observation.context.purchasingContext.contextRevision,
      currentSourceRevisions: [
        {
          revision: stableRevision({
            currency: observation.context.purchasingContext.currencyResolution.resolutionRevision,
            settings: observation.context.purchasingContext.commercialSettingsDecision.decisionRevision,
          }),
          source: 'customer-commerce-policy',
        },
        { revision: proposal.purchaseValue.sourceRevision, source: 'purchase-proposal' },
        { revision: String(observation.profileRevision), source: 'purchasing-profile' },
        { revision: stableRevision(observation.storefront), source: 'storefront-context' },
      ],
      marketId: observation.context.commercialScope.marketId,
      purchaseValue: bundlePurchaseValue,
    }).pipe(Effect.mapError(unavailable));
    const currentness = preparedOrderCurrentness({
      bundlePurchaseValue,
      facts,
      observedAt: now,
      request,
      scope,
      validUntil,
    });
    if (DateTime.toEpochMillis(yield* DateTime.now) >= validUntil) {
      return yield* unavailable('Order preflight evidence expired during remote resolution');
    }
    const finalBindingEvidence = {
      binding: prepared.binding,
      observedAt: prepared.observedAt,
      provenance: prepared.provenance,
      validUntil: prepared.validUntil,
    };
    const prepareCurrentness = yield* prepareOrderPurchaseApprovalRevalidation(
      { buyerPrincipalId: proposal.identity.buyer.principalId, storefrontId: proposal.context.storefrontId },
      { ...claimed, validUntil: DateTime.makeUnsafe(validUntil) },
      finalBindingEvidence,
      { bundlePurchaseValue, currentness },
      context,
    );
    return {
      before,
      bundlePurchaseValue,
      candidate,
      claimed: { ...claimed, validUntil: DateTime.makeUnsafe(validUntil) },
      compositionRevision: context.compositionRevision,
      currentness,
      finalBindingEvidence,
      operationTime,
      prepareCurrentness,
      validUntil,
    };
  },
);

/** Rechecks the complete request and pricing-owner snapshot on the actual commit executor. */
export const recheckOrderApprovalFinalizationEvidence = Effect.fn('OrderApprovalFinalization.recheckActionEvidence')(
  function* recheckActionEvidence(
    transaction: ScopedTransactionExecutor,
    scope: OperationalScope,
    prepared: Effect.Success<ReturnType<typeof prepareOrderApprovalFinalizationEvidence>>,
  ) {
    const current = yield* loadOrderApprovalFinalizationSnapshot(
      transaction,
      scope,
      prepared.before.snapshot.request.requestRef,
      false,
    );
    yield* verifyOrderFinalizationSnapshot(
      prepared.before.snapshot,
      current,
      prepared.validUntil,
      DateTime.toEpochMillis(yield* DateTime.now),
    );
    const pricing = yield* loadPurchasePricingContextSnapshot(
      transaction,
      scope,
      current.request,
      prepared.operationTime,
    ).pipe(Effect.mapError(unavailable));
    if (stableRevision(pricing) !== stableRevision(prepared.before.pricing)) {
      return yield* unavailable('Order pricing owner state changed after preflight');
    }
    return yield* Effect.void;
  },
);

export const commitPreparedOrderApprovalFinalization = Effect.fn('OrderApprovalFinalization.commitPrepared')(
  function* commitPrepared(
    transaction: ScopedTransactionExecutor,
    scope: OperationalScope,
    input: {
      readonly actionInvocationId: string;
      readonly prepared: Effect.Success<ReturnType<typeof prepareOrderApprovalFinalizationEvidence>>;
    },
  ) {
    const { prepared } = input;
    yield* recheckOrderApprovalFinalizationEvidence(transaction, scope, prepared);
    const { revalidate, trusted } = yield* prepared.prepareCurrentness(
      transaction,
      scope,
      prepared.compositionRevision,
    );
    const result = yield* revalidatePurchaseApprovalFromVerifiedOrder(
      transaction,
      scope,
      trusted,
      input.actionInvocationId,
    );
    yield* revalidate();
    yield* recheckOrderApprovalFinalizationEvidence(transaction, scope, prepared);
    return result;
  },
);
