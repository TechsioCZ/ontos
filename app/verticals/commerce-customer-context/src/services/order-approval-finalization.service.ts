const terminalWitnessAdmitted = ({
  candidate,
  input,
  nativeNow,
  request,
  scope,
  witness,
}: {
  readonly candidate: FinalCartCandidate;
  readonly input: RecoverRevalidationRequest;
  readonly nativeNow: DateTime.DateTime;
  readonly request: OrderRequestSnapshot;
  readonly scope: OperationalScope;
  readonly witness: TerminalWitness;
}): boolean => {
  const explicitTerminal = witness.request.status === witness.terminalStatus;
  const ownerExpiry =
    witness.terminalStatus === 'EXPIRED' &&
    witness.request.status === 'APPROVED' &&
    DateTime.toEpochMillis(witness.request.expiresAt) <= DateTime.toEpochMillis(witness.observedAt);
  const { originalProof } = witness;
  return (
    (explicitTerminal || ownerExpiry) &&
    !DateTime.isGreaterThan(witness.observedAt, nativeNow) &&
    Schema.toEquivalence(OrderCommitmentApprovalRequestSnapshotSchema)(witness.request, request) &&
    sameRef(witness.requestRef, input.requestRef) &&
    witness.idempotencyKey === input.idempotencyKey &&
    witness.commitmentCorrelationId === input.commitmentCorrelationId &&
    sameBinding(witness.finalBinding, input.finalBinding) &&
    sameRef(witness.candidateRef, candidate.candidateRef) &&
    witness.candidateHash === candidate.candidateHash &&
    (Option.isNone(originalProof) ||
      originalProofAdmitted({ input, original: originalProof.value, proposal: request.proposal, request, scope }))
  );
};

