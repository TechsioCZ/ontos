const sameRef = (
  left: { moduleId: string; resourceId: string; resourceType: string; tenantId: string },
  right: { moduleId: string; resourceId: string; resourceType: string; tenantId: string },
) =>
  left.moduleId === right.moduleId &&
  left.resourceId === right.resourceId &&
  left.resourceType === right.resourceType &&
  left.tenantId === right.tenantId;
const sameBinding = (
  left: RevalidateOrderPurchaseApprovalPayload['finalBinding'],
  right: RevalidateOrderPurchaseApprovalPayload['finalBinding'],
) =>
  sameRef(left.attemptRef, right.attemptRef) &&
  sameRef(left.bundleRef, right.bundleRef) &&
  left.bundleHash === right.bundleHash &&
  left.bundleVersion === right.bundleVersion;
