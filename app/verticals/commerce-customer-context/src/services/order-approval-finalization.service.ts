const orderApprovalFinalizationRemote = Effect.fn('OrderApprovalFinalization.remote')(function* remote(
  scope: OperationalScope,
  compositionRevision?: string,
) {
  const access = yield* ContextAccess;
  const composition = yield* ActiveApplicationCompositionService;
  const authorize = Effect.fn('OrderApprovalFinalization.authorize')(function* authorize(
    operation: typeof operationSchema.Type,
  ) {
    const configured = yield* grants.pipe(Effect.mapError(unavailable));
    if (
      scope.authMethod !== 'api_key' ||
      !isVerifiedGatewayPrincipalContext(scope) ||
      scope.impersonatedByPrincipalId !== undefined ||
      scope.legalEntityId === undefined
    ) {
      return yield* rejected();
    }
    const matched = configured.filter(
      (grant) =>
        grant.principalId === scope.principalId &&
        grant.authenticationNamespaceId === scope.authenticationNamespaceId &&
        grant.tenantId === scope.tenantId &&
        grant.legalEntityId === scope.legalEntityId &&
        grant.operations.includes(operation),
    );
    const [grant] = matched;
    if (matched.length !== 1 || grant === undefined) {
      return yield* rejected();
    }
    const permissions = yield* access.modules({
      legalEntityId: scope.legalEntityId,
      moduleIds: ['commerce.customer-context'],
      principalId: scope.principalId,
      tenantId: scope.tenantId,
    });
    const [permission] = permissions;
    if (
      permissions.length !== 1 ||
      permission?.key !== 'commerce.customer-context' ||
      permission.decision === 'unavailable'
    ) {
      return yield* unavailable('Owner module access is indeterminate');
    }
    if (permission.decision !== 'allowed') {
      return yield* rejected();
    }
    return grant;
  });
  const activeRevision = Effect.fn('OrderApprovalFinalization.activeRevision')(function* activeRevision() {
    const active = yield* composition.load.pipe(
      Effect.flatMap(validateActiveApplicationCompositionSnapshot),
      Effect.mapError(unavailable),
    );
    if (compositionRevision !== undefined && compositionRevision !== active.composition.revision) {
      return yield* unavailable('The request composition is no longer active');
    }
    return active.composition.revision;
  });
  const gateway = Effect.fn('OrderApprovalFinalization.gateway')(function* gateway(
    audience: 'commerce-cart' | 'commerce-order',
  ) {
    if (scope.legalEntityId === undefined) {
      return yield* rejected();
    }
    const configured = yield* gatewayConfiguration.pipe(Effect.mapError(unavailable));
    const revision = yield* activeRevision();
    const assertion = yield* issueApiKeyGatewayContext(
      { audience, compositionRevision: revision, legalEntityId: scope.legalEntityId },
      { apiKey: configured.apiKey, baseUrl: configured.shellBaseUrl, requestCorrelation: scope.correlationId },
    ).pipe(Effect.mapError(unavailable));
    if (assertion.compositionRevision !== revision || assertion.expiresAt * 1000 <= (yield* Clock.currentTimeMillis)) {
      return yield* unavailable('The owner gateway assertion is stale');
    }
    return { authorization: `Bearer ${assertion.token}`, configured, revision };
  });
  const loadCandidate = Effect.fn('OrderApprovalFinalization.loadCandidate')(function* loadCandidate(
    input: { candidateHash: string; candidateRef: RevalidateOrderPurchaseApprovalPayload['candidateRef'] },
    request: typeof OrderCommitmentApprovalRequestSnapshotSchema.Type,
  ) {
    if (input.candidateRef.tenantId !== scope.tenantId) {
      return yield* rejected();
    }
    const credential = yield* gateway('commerce-cart');
    const candidate = yield* executeFinalCartCandidateWithAuthorization(
      input,
      credential.authorization,
      scope.correlationId,
      { baseUrl: credential.configured.cartBaseUrl, compositionRevision: credential.revision },
    ).pipe(
      Effect.flatMap(Schema.decodeUnknownEffect(Schema.toType(FinalCartCandidateSchema))),
      Effect.mapError(unavailable),
    );
    if (!candidateAdmitted({ candidate, input, request, scope })) {
      return yield* rejected();
    }
    return candidate;
  });
  return { activeRevision, authorize, gateway, loadCandidate };
});

export const loadOrderApprovalFinalizationSnapshot = Effect.fn('OrderApprovalFinalization.loadRequest')(
  function* loadRequest(
    transaction: ScopedTransactionExecutor,
    scope: OperationalScope,
    requestRef: RevalidateOrderPurchaseApprovalPayload['requestRef'],
    allowTerminal: boolean,
  ) {
    if (scope.legalEntityId === undefined || requestRef.tenantId !== scope.tenantId) {
      return yield* rejected();
    }
    const [row] = yield* transaction
      .invoke(readCurrentPurchaseApprovalRevalidationRoutine, [{ requestRef }])
      .pipe(Effect.mapError(unavailable));
    if (row === undefined) {
      return yield* unavailable('The persisted approval request is unavailable');
    }
    const snapshot = yield* Schema.decodeUnknownEffect(OrderFinalizationSnapshotSchema)(row.result).pipe(
      Effect.mapError(unavailable),
    );
    const { request } = snapshot;
    const terminal = allowTerminal && TERMINAL_STATUSES.has(request.status);
    if (!retainedRequestAdmitted({ request, requestRef, scope, terminal })) {
      return yield* rejected();
    }
    return snapshot;
  },
);

