const retainedRequestAdmitted = ({
  request,
  requestRef,
  scope,
  terminal,
}: {
  readonly request: OrderRequestSnapshot;
  readonly requestRef: OrderRequestSnapshot['requestRef'];
  readonly scope: OperationalScope;
  readonly terminal: boolean;
}): boolean => {
  const { proposal } = request;
  const requestStateAdmitted =
    sameRef(request.requestRef, requestRef) &&
    (terminal || request.status === 'APPROVED' || request.status === 'CONSUMED');
  const proposalStateAdmitted =
    proposal.state === 'CURRENT' || proposal.state === 'CONSUMED' || (terminal && proposal.state === 'SUPERSEDED');
  return (
    requestStateAdmitted &&
    proposalStateAdmitted &&
    // The subject of every operation is the buyer the approval belongs to (DESIGN D8).
    proposal.identity.buyer.principalId === scope.principalId &&
    proposal.context.tenantId === scope.tenantId &&
    proposal.context.sellingLegalEntityId === scope.legalEntityId &&
    proposal.identity.buyer.tenantId === scope.tenantId &&
    computePurchaseProposalCanonicalHash(proposal) === proposal.canonicalHash &&
    proposal.payment === 'NONE' &&
    proposal.reservation === 'NONE' &&
    proposal.sourceCart.cartRef.moduleId === 'commerce.cart' &&
    proposal.sourceCart.cartRef.resourceType === 'commerce.cart.cart' &&
    proposal.sourceCart.cartRef.tenantId === scope.tenantId
  );
};

const candidateAdmitted = ({
  candidate,
  input,
  request,
  scope,
}: {
  readonly candidate: FinalCartCandidate;
  readonly input: { readonly candidateHash: string; readonly candidateRef: FinalCartCandidate['candidateRef'] };
  readonly request: OrderRequestSnapshot;
  readonly scope: OperationalScope;
}): boolean => {
  const { proposal } = request;
  return (
    sameRef(candidate.candidateRef, input.candidateRef) &&
    candidate.candidateHash === input.candidateHash &&
    candidate.tenantId === scope.tenantId &&
    candidate.legalEntityId === scope.legalEntityId &&
    candidate.buyerPrincipalId === proposal.identity.buyer.principalId &&
    candidate.storefrontId === proposal.context.storefrontId &&
    sameRef(candidate.approval.requestRef, request.requestRef) &&
    sameRef(candidate.approval.proposalRevisionRef, proposal.proposalRevisionRef) &&
    candidate.approval.proposalHash === proposal.canonicalHash &&
    sameRef(candidate.sourceCart.cartRef, proposal.sourceCart.cartRef) &&
    String(candidate.sourceCart.revision) === proposal.sourceCart.revision
  );
};

const originalProofAdmitted = ({
  input,
  original,
  proposal,
  request,
  scope,
}: {
  readonly input: RecoverRevalidationRequest;
  readonly original: typeof OrderCommitmentApprovalProofSchema.Type;
  readonly proposal: OrderRequestSnapshot['proposal'];
  readonly request: OrderRequestSnapshot;
  readonly scope: OperationalScope;
}): boolean =>
  original.evidence.actorPrincipalId === scope.principalId &&
  sameRef(original.requestRef, request.requestRef) &&
  sameRef(original.proposalRevisionRef, proposal.proposalRevisionRef) &&
  original.evidence.proposalHash === proposal.canonicalHash &&
  original.evidence.commitmentCorrelationId === input.commitmentCorrelationId &&
  original.evidence.finalBindingEvidence !== undefined &&
  sameBinding(original.evidence.finalBindingEvidence.binding, input.finalBinding);

const terminalWitnessAdmitted = ({
  candidate,
  input,
  nativeNow,
  request,
  scope,
  witness,
}: {
  readonly candidate: FinalCartCandidate;
  readonly input: RecoverRevalidationRequest;
  readonly nativeNow: DateTime.DateTime;
  readonly request: OrderRequestSnapshot;
  readonly scope: OperationalScope;
  readonly witness: TerminalWitness;
}): boolean => {
  const explicitTerminal = witness.request.status === witness.terminalStatus;
  const ownerExpiry =
    witness.terminalStatus === 'EXPIRED' &&
    witness.request.status === 'APPROVED' &&
    DateTime.toEpochMillis(witness.request.expiresAt) <= DateTime.toEpochMillis(witness.observedAt);
  const { originalProof } = witness;
  return (
    (explicitTerminal || ownerExpiry) &&
    !DateTime.isGreaterThan(witness.observedAt, nativeNow) &&
    Schema.toEquivalence(OrderCommitmentApprovalRequestSnapshotSchema)(witness.request, request) &&
    sameRef(witness.requestRef, input.requestRef) &&
    witness.idempotencyKey === input.idempotencyKey &&
    witness.commitmentCorrelationId === input.commitmentCorrelationId &&
    sameBinding(witness.finalBinding, input.finalBinding) &&
    sameRef(witness.candidateRef, candidate.candidateRef) &&
    witness.candidateHash === candidate.candidateHash &&
    (Option.isNone(originalProof) ||
      originalProofAdmitted({ input, original: originalProof.value, proposal: request.proposal, request, scope }))
  );
};

const foundRevalidationAdmitted = ({
  input,
  request,
  result,
  scope,
}: {
  readonly input: RecoverRevalidationRequest;
  readonly request: OrderRequestSnapshot;
  readonly result: typeof RevalidatePurchaseApprovalResultSchema.Type;
  readonly scope: OperationalScope;
}): boolean => {
  const { revalidation } = result;
  const binding = revalidation.evidence.finalBindingEvidence?.binding;
  return (
    result.outcome === 'APPROVAL_VALID' &&
    revalidation.status === 'APPROVAL_VALID' &&
    revalidation.evidence.actorPrincipalId === scope.principalId &&
    sameRef(revalidation.requestRef, request.requestRef) &&
    sameRef(revalidation.proposalRevisionRef, request.proposal.proposalRevisionRef) &&
    revalidation.evidence.proposalHash === request.proposal.canonicalHash &&
    revalidation.evidence.commitmentCorrelationId === input.commitmentCorrelationId &&
    binding !== undefined &&
    sameBinding(binding, input.finalBinding)
  );
};

