export const orderApprovalFinalizationService = Effect.fn('OrderApprovalFinalization.services')((
  transaction: ScopedTransactionExecutor,
  scope: OperationalScope,
) => {
  const recoverRevalidation = Effect.fn('OrderApprovalFinalization.recoverRevalidation')(function* recoverRevalidation(
    input: RecoverRevalidationRequest,
    request: OrderRequestSnapshot,
    candidate: FinalCartCandidate,
  ) {
    const candidateIdentity = { candidateHash: candidate.candidateHash, candidateRef: candidate.candidateRef };
    const [row] = yield* transaction
      .invoke(readOrderServiceApprovalProofRoutine, [
        {
          actorPrincipalId: scope.principalId,
          candidateHash: candidate.candidateHash,
          candidateRef: candidate.candidateRef,
          commitmentCorrelationId: input.commitmentCorrelationId,
          finalBinding: input.finalBinding,
          idempotencyKey: input.idempotencyKey,
          operation: input.operation,
          requestRef: input.requestRef,
        },
      ])
      .pipe(Effect.mapError(unavailable));
    if (row === undefined) {
      return yield* unavailable('The retained approval recovery identity is unavailable');
    }
    const recovered = yield* Schema.decodeUnknownEffect(
      Schema.Union([
        Schema.Struct({ recovery: Schema.Literal('NOT_FOUND') }),
        Schema.Struct({ recovery: Schema.Literal('CONFLICT') }),
        Schema.Struct({ recovery: Schema.Literal('FOUND'), result: RevalidatePurchaseApprovalResultSchema }),
        Schema.Struct({
          recovery: Schema.Literal('REQUEST_TERMINAL'),
          witness: OrderServiceApprovalTerminalWitnessSchema,
        }),
      ]),
    )(row.result).pipe(Effect.mapError(unavailable));
    if (recovered.recovery === 'CONFLICT') {
      return yield* new PurchasingApprovalRejected({
        code: 'IDEMPOTENCY_CONFLICT',
        reason: 'The original approval proof intent does not match this exact service and purchase',
        retryable: false,
      });
    }
    if (recovered.recovery === 'NOT_FOUND') {
      return { operation: input.operation, ...candidateIdentity, recovery: 'NOT_FOUND' as const };
    }
    if (recovered.recovery === 'REQUEST_TERMINAL') {
      const { witness } = recovered;
      const nativeNow = yield* DateTime.now;
      if (!terminalWitnessAdmitted({ candidate, input, nativeNow, request, scope, witness })) {
        return yield* rejected();
      }
      // The original proof is preserved when present. This lifecycle witness is
      // neither proof issuance nor an assertion about whether an Order committed.
      return { operation: input.operation, ...candidateIdentity, recovery: 'REQUEST_TERMINAL' as const, witness };
    }
    if (!foundRevalidationAdmitted({ input, request, result: recovered.result, scope })) {
      return yield* rejected();
    }
    // The original proof, status, history and validity window are never refreshed by a read.
    return {
      operation: input.operation,
      ...candidateIdentity,
      recovery: 'FOUND' as const,
      result: recovered.result,
    };
  });
  const verifyRetainedProof = Effect.fn('OrderApprovalFinalization.verifyRetainedProof')(function* verifyRetainedProof(
    input: ProofRetainedRequest,
    request: OrderRequestSnapshot,
    candidate: FinalCartCandidate,
  ) {
    const { proposal } = request;
    const [row] = yield* transaction
      .invoke(readOrderServiceApprovalProofRoutine, [
        {
          actorPrincipalId: scope.principalId,
          finalBinding: input.finalBinding,
          requestRef: input.requestRef,
          revalidationRef: input.revalidationRef,
        },
      ])
      .pipe(Effect.mapError(unavailable));
    if (row === undefined) {
      return yield* unavailable('The retained approval proof is unavailable');
    }
    const retained = yield* Schema.decodeUnknownEffect(
      Schema.Struct({
        proof: OrderCommitmentApprovalProofSchema,
        proofActorPrincipalId: PrincipalIdSchema.pipe(Schema.decodeTo(Schema.String)),
        proposal: PurchaseProposalRevisionSchema,
        request: OrderCommitmentApprovalRequestSnapshotSchema,
      }),
    )(row.result).pipe(Effect.mapError(unavailable));
    const proofActor = retained.proofActorPrincipalId;
    if (!retainedProofAdmitted({ input, proofActor, request, retained, scope })) {
      return yield* rejected();
    }
    const issuer =
      proofActor === proposal.identity.buyer.principalId
        ? { buyerPrincipalId: proofActor, kind: 'BUYER' as const }
        : { kind: 'ORDER_SERVICE' as const, serviceProofActorPrincipalId: proofActor };
    return {
      candidateHash: candidate.candidateHash,
      candidateRef: candidate.candidateRef,
      operation: input.operation,
      ...retained,
      issuer,
    };
  });
  return Effect.succeed({
    load: (input: OrderServiceApprovalEvidenceRequest) => loadOrderFinalizationReadSnapshot(transaction, scope, input),
    recoverRevalidation,
    verifyRetainedProof,
  });
});

