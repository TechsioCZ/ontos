const retainedProofAdmitted = ({
  input,
  proofActor,
  request,
  retained,
}: {
  readonly input: ProofRetainedRequest;
  readonly proofActor: string;
  readonly request: OrderRequestSnapshot;
  readonly retained: {
    readonly proof: typeof OrderCommitmentApprovalProofSchema.Type;
    readonly proposal: typeof PurchaseProposalRevisionSchema.Type;
    readonly request: OrderRequestSnapshot;
  };
}): boolean => {
  const { proposal } = request;
  return (
    proofActor === proposal.identity.buyer.principalId &&
    sameRef(retained.request.requestRef, request.requestRef) &&
    retained.proposal.canonicalHash === proposal.canonicalHash &&
    computePurchaseProposalCanonicalHash(retained.proposal) === proposal.canonicalHash &&
    approvalProofMatchesRetainedRequest(
      { ...input, counterpartyRef: proposal.identity.counterpartyRef, storefrontId: proposal.context.storefrontId },
      retained.request,
      retained.proposal,
      retained.proof,
      proofActor,
    )
  );
};

/**
 * The verified subject is the approval's buyer (checked on every load); the verified actor names the calling
 * module, which `authorize` gates per operation.
 */
export const orderApprovalFinalizationService = Effect.fn('OrderApprovalFinalization.services')(
  function* orderFinalizationServices(
    transaction: ScopedTransactionExecutor,
    scope: OperationalScope,
    compositionRevision?: string,
  ) {
    const composition = yield* ActiveApplicationCompositionService;
    const dependencies = yield* Effect.context<FinalizationRequirements>();
    const authorize = Effect.fn('OrderApprovalFinalization.authorize')(function* authorize(
      operation: typeof operationSchema.Type,
    ) {
      // The calling module is the actor the Shell signed (DESIGN D6); the subject is the buyer, not a service.
      // The owner module's installation is the module-state gate's fact, not a second permission check (O62).
      const actor = readVerifiedGatewayActor(scope);
      const admitted =
        actor !== undefined &&
        isVerifiedGatewayPrincipalContext(scope) &&
        scope.impersonatedByPrincipalId === undefined &&
        scope.legalEntityId !== undefined &&
        (callerOperations.get(actor.appId)?.includes(operation) ?? false);
      return yield* admitted ? Effect.void : rejected();
    });
    const activeRevision = Effect.fn('OrderApprovalFinalization.activeRevision')(function* activeRevision() {
      const active = yield* composition.load.pipe(
        Effect.flatMap(validateActiveApplicationCompositionSnapshot),
        Effect.mapError(unavailable),
      );
      if (compositionRevision !== undefined && compositionRevision !== active.composition.revision) {
        return yield* unavailable('The request composition is no longer active');
      }
      return active.composition.revision;
    });
    const gateway = Effect.fn('OrderApprovalFinalization.gateway')(function* gateway(
      audience: 'commerce-cart' | 'commerce-order',
    ) {
      if (scope.legalEntityId === undefined) {
        return yield* rejected();
      }
      const configured = yield* gatewayConfiguration.pipe(Effect.mapError(unavailable));
      const revision = yield* activeRevision();
      const crypto = yield* Crypto.Crypto;
      const assertion = yield* acquireDelegatedGatewayContext(
        {
          audience,
          legalEntityScope: 'subject',
          requestCorrelation: scope.correlationId,
          subject: { _tag: 'Assertion', scope },
        },
        crypto,
      ).pipe(Effect.mapError(unavailable));
      if (
        assertion.compositionRevision !== revision ||
        assertion.expiresAt * 1000 <= (yield* Clock.currentTimeMillis)
      ) {
        return yield* unavailable('The owner gateway assertion is stale');
      }
      return { authorization: assertion.authorization, configured, revision };
    });
    const loadRequest = Effect.fn('OrderApprovalFinalization.loadRequest')(function* loadRequest(
      requestRef: RevalidateOrderPurchaseApprovalPayload['requestRef'],
      allowTerminal: boolean,
    ) {
      if (scope.legalEntityId === undefined || requestRef.tenantId !== scope.tenantId) {
        return yield* rejected();
      }
      const [row] = yield* transaction
        .invoke(readCurrentPurchaseApprovalRevalidationRoutine, [{ requestRef }])
        .pipe(Effect.mapError(unavailable));
      if (row === undefined) {
        return yield* unavailable('The persisted approval request is unavailable');
      }
      const snapshot = yield* Schema.decodeUnknownEffect(
        Schema.Struct({
          request: OrderCommitmentApprovalRequestSnapshotSchema,
          sourceRevisions: RevalidatePurchaseApprovalInputSchema.fields.sourceRevisions,
        }),
      )(row.result).pipe(Effect.mapError(unavailable));
      const { request } = snapshot;
      const terminal = allowTerminal && TERMINAL_STATUSES.has(request.status);
      if (!retainedRequestAdmitted({ request, requestRef, scope, terminal })) {
        return yield* rejected();
      }
      return snapshot;
    });
    const loadCandidate = Effect.fn('OrderApprovalFinalization.loadCandidate')(function* loadCandidate(
      input: { candidateHash: string; candidateRef: RevalidateOrderPurchaseApprovalPayload['candidateRef'] },
      request: typeof OrderCommitmentApprovalRequestSnapshotSchema.Type,
    ) {
      if (input.candidateRef.tenantId !== scope.tenantId) {
        return yield* rejected();
      }
      const credential = yield* gateway('commerce-cart');
      const candidate = yield* executeFinalCartCandidateWithAuthorization(
        input,
        credential.authorization,
        scope.correlationId,
        { baseUrl: credential.configured.cartBaseUrl, compositionRevision: credential.revision },
      ).pipe(
        Effect.flatMap(Schema.decodeUnknownEffect(Schema.toType(FinalCartCandidateSchema))),
        Effect.mapError(unavailable),
      );
      if (!candidateAdmitted({ candidate, input, request, scope })) {
        return yield* rejected();
      }
      return candidate;
    });
    const readApprovedIdentity = Effect.fn('OrderApprovalFinalization.readApprovedIdentity')(
      function* readApprovedIdentity(
        input: Extract<OrderServiceApprovalEvidenceRequest, { readonly operation: 'LOAD_APPROVED_IDENTITY' }>,
        request: OrderRequestSnapshot,
      ) {
        const { proposal } = request;
        if (request.status !== 'APPROVED' || proposal.state !== 'CURRENT') {
          return yield* rejected();
        }
        const revision = yield* activeRevision();
        const pricingContext = yield* resolveOrderFinalizationPricingContext(
          transaction,
          scope,
          request,
          revision,
          DateTime.formatIso(input.operationTime),
        ).pipe(Effect.mapError(unavailable));
        return {
          buyerPrincipalId: proposal.identity.buyer.principalId,
          cartRef: proposal.sourceCart.cartRef,
          cartRevision: proposal.sourceCart.revision,
          counterpartyRef: proposal.identity.counterpartyRef,
          legalEntityId: scope.legalEntityId,
          operation: input.operation,
          pricingContext,
          proposal,
          proposalHash: proposal.canonicalHash,
          proposalRevisionRef: proposal.proposalRevisionRef,
          requestRef: request.requestRef,
          storefrontId: proposal.context.storefrontId,
          tenantId: scope.tenantId,
        };
      },
    );
    const recoverRevalidation = Effect.fn('OrderApprovalFinalization.recoverRevalidation')(
      function* recoverRevalidation(
        input: RecoverRevalidationRequest,
        request: OrderRequestSnapshot,
        candidate: FinalCartCandidate,
      ) {
        const candidateIdentity = { candidateHash: candidate.candidateHash, candidateRef: candidate.candidateRef };
        const [row] = yield* transaction
          .invoke(readOrderServiceApprovalProofRoutine, [
            {
              actorPrincipalId: scope.principalId,
              candidateHash: candidate.candidateHash,
              candidateRef: candidate.candidateRef,
              commitmentCorrelationId: input.commitmentCorrelationId,
              finalBinding: input.finalBinding,
              idempotencyKey: input.idempotencyKey,
              operation: input.operation,
              requestRef: input.requestRef,
            },
          ])
          .pipe(Effect.mapError(unavailable));
        if (row === undefined) {
          return yield* unavailable('The retained approval recovery identity is unavailable');
        }
        const recovered = yield* Schema.decodeUnknownEffect(
          Schema.Union([
            Schema.Struct({ recovery: Schema.Literal('NOT_FOUND') }),
            Schema.Struct({ recovery: Schema.Literal('CONFLICT') }),
            Schema.Struct({ recovery: Schema.Literal('FOUND'), result: RevalidatePurchaseApprovalResultSchema }),
            Schema.Struct({
              recovery: Schema.Literal('REQUEST_TERMINAL'),
              witness: OrderServiceApprovalTerminalWitnessSchema,
            }),
          ]),
        )(row.result).pipe(Effect.mapError(unavailable));
        if (recovered.recovery === 'CONFLICT') {
          return yield* new PurchasingApprovalRejected({
            code: 'IDEMPOTENCY_CONFLICT',
            reason: 'The original approval proof intent does not match this exact service and purchase',
            retryable: false,
          });
        }
        if (recovered.recovery === 'NOT_FOUND') {
          return { operation: input.operation, ...candidateIdentity, recovery: 'NOT_FOUND' as const };
        }
        if (recovered.recovery === 'REQUEST_TERMINAL') {
          const { witness } = recovered;
          const nativeNow = yield* DateTime.now;
          if (!terminalWitnessAdmitted({ candidate, input, nativeNow, request, scope, witness })) {
            return yield* rejected();
          }
          // The original proof is preserved when present. This lifecycle witness is
          // neither proof issuance nor an assertion about whether an Order committed.
          return { operation: input.operation, ...candidateIdentity, recovery: 'REQUEST_TERMINAL' as const, witness };
        }
        if (!foundRevalidationAdmitted({ input, request, result: recovered.result, scope })) {
          return yield* rejected();
        }
        // The original proof, status, history and validity window are never refreshed by a read.
        return {
          operation: input.operation,
          ...candidateIdentity,
          recovery: 'FOUND' as const,
          result: recovered.result,
        };
      },
    );
    const verifyRetainedProof = Effect.fn('OrderApprovalFinalization.verifyRetainedProof')(
      function* verifyRetainedProof(
        input: ProofRetainedRequest,
        request: OrderRequestSnapshot,
        candidate: FinalCartCandidate,
      ) {
        const [row] = yield* transaction
          .invoke(readOrderServiceApprovalProofRoutine, [
            {
              actorPrincipalId: scope.principalId,
              finalBinding: input.finalBinding,
              requestRef: input.requestRef,
              revalidationRef: input.revalidationRef,
            },
          ])
          .pipe(Effect.mapError(unavailable));
        if (row === undefined) {
          return yield* unavailable('The retained approval proof is unavailable');
        }
        const retained = yield* Schema.decodeUnknownEffect(
          Schema.Struct({
            proof: OrderCommitmentApprovalProofSchema,
            proofActorPrincipalId: PrincipalIdSchema.pipe(Schema.decodeTo(Schema.String)),
            proposal: PurchaseProposalRevisionSchema,
            request: OrderCommitmentApprovalRequestSnapshotSchema,
          }),
        )(row.result).pipe(Effect.mapError(unavailable));
        const proofActor = retained.proofActorPrincipalId;
        if (!retainedProofAdmitted({ input, proofActor, request, retained })) {
          return yield* rejected();
        }
        return {
          candidateHash: candidate.candidateHash,
          candidateRef: candidate.candidateRef,
          operation: input.operation,
          ...retained,
          issuer: { buyerPrincipalId: proofActor, kind: 'BUYER' as const },
        };
      },
    );
    const read = Effect.fn('OrderApprovalFinalization.read')(function* read(
      input: OrderServiceApprovalEvidenceRequest,
    ) {
      // Recovery retains the original issuing service's existing REVALIDATE grant.
      yield* authorize(input.operation === 'RECOVER_REVALIDATION' ? 'REVALIDATE' : input.operation);
      const { request } = yield* loadRequest(input.requestRef, input.operation === 'RECOVER_REVALIDATION');
      if (input.operation === 'LOAD_APPROVED_IDENTITY') {
        return yield* readApprovedIdentity(input, request);
      }
      const candidate = yield* loadCandidate(input, request);
      const candidateIdentity = { candidateHash: candidate.candidateHash, candidateRef: candidate.candidateRef };
      if (input.operation === 'LOAD_PROPOSAL') {
        return { operation: input.operation, ...candidateIdentity, proposal: request.proposal, request };
      }
      if (input.operation === 'RESOLVE_PAYMENT_TERMS') {
        const resolution = yield* resolveOrderFinalizationPaymentTerms(
          transaction,
          scope,
          request,
          candidate,
          yield* activeRevision(),
        ).pipe(Effect.mapError(unavailable));
        return { operation: input.operation, ...candidateIdentity, resolution };
      }
      if (input.operation === 'RECOVER_REVALIDATION') {
        return yield* recoverRevalidation(input, request, candidate);
      }
      return yield* verifyRetainedProof(input, request, candidate);
    });
    const revalidate = Effect.fn('OrderApprovalFinalization.revalidate')(function* revalidate(
      payload: RevalidateOrderPurchaseApprovalPayload,
      actionInvocationId: string,
    ) {
      yield* authorize('REVALIDATE');
      const snapshot = yield* loadRequest(payload.requestRef, false);
      const { request } = snapshot;
      const { proposal } = request;
      if (request.status !== 'APPROVED' || request.lastDecisionRef === null) {
        return yield* rejected();
      }
      const { candidate, credential } = yield* Effect.all(
        { candidate: loadCandidate(payload, request), credential: gateway('commerce-order') },
        { concurrency: 1 },
      );
      const query = yield* Schema.decodeUnknownEffect(Schema.toType(PreparedOrderApprovalBindingRequestSchema))({
        binding: payload.finalBinding,
        candidateHash: candidate.candidateHash,
        candidateRef: candidate.candidateRef,
        commitmentCorrelationId: payload.commitmentCorrelationId,
        proposalHash: proposal.canonicalHash,
        proposalRevisionRef: proposal.proposalRevisionRef,
        requestRef: request.requestRef,
      }).pipe(Effect.mapError(unavailable));
      const prepared = yield* executePreparedOrderApprovalBindingWithAuthorization(
        query,
        credential.authorization,
        scope.correlationId,
        { baseUrl: credential.configured.orderBaseUrl, compositionRevision: credential.revision },
      ).pipe(
        Effect.flatMap(Schema.decodeUnknownEffect(Schema.toType(PreparedOrderApprovalBindingResponseSchema))),
        Effect.mapError(unavailable),
      );
      const now = yield* DateTime.now;
      if (!preparedBindingAdmitted({ candidate, now, payload, prepared, request, scope })) {
        return yield* rejected();
      }
      const claimed = yield* Schema.decodeUnknownEffect(Schema.toType(RevalidatePurchaseApprovalInputSchema))({
        buyerPermission: 'ALLOWED',
        checkedAt: now,
        commitmentCorrelationId: payload.commitmentCorrelationId,
        counterpartyRef: proposal.identity.counterpartyRef,
        decisionBundleHash: request.decisionBundleHash,
        decisionBundleVersion: request.decisionBundleVersion,
        decisionRef: request.lastDecisionRef,
        expectedProposalHash: proposal.canonicalHash,
        finalBinding: payload.finalBinding,
        hierarchyRef: request.route.hierarchyRef,
        idempotencyKey: payload.idempotencyKey,
        profileState: 'ACTIVE',
        proposalRevisionRef: proposal.proposalRevisionRef,
        requestRef: request.requestRef,
        routeCurrent: true,
        routeRef: request.route.routeRef,
        sourceRevisions: snapshot.sourceRevisions,
        storefrontId: proposal.context.storefrontId,
        validUntil: DateTime.makeUnsafe(
          Math.min(
            DateTime.toEpochMillis(request.expiresAt),
            DateTime.toEpochMillis(proposal.expiresAt),
            DateTime.toEpochMillis(now) + 30_000,
          ),
        ),
      }).pipe(Effect.mapError(unavailable));
      const bundlePurchaseValue = yield* Schema.decodeUnknownEffect(Schema.toType(PurchaseValueSchema))(
        prepared.bundlePurchaseValue,
      ).pipe(Effect.mapError(unavailable));
      const revision = yield* activeRevision();
      const currentness: PurchaseLimitEvaluationCurrentnessPortService = {
        resolveCurrent: ({ observedAt }) =>
          resolveOrderCurrentnessFacts(transaction, scope, request, bundlePurchaseValue, observedAt, revision).pipe(
            Effect.provideContext(dependencies),
          ),
      };
      const trusted = yield* resolveOrderPurchaseApprovalRevalidation(
        transaction,
        scope,
        { buyerPrincipalId: proposal.identity.buyer.principalId, storefrontId: proposal.context.storefrontId },
        claimed,
        {
          binding: prepared.binding,
          observedAt: prepared.observedAt,
          provenance: prepared.provenance,
          validUntil: prepared.validUntil,
        },
        { bundlePurchaseValue, currentness },
      );
      return yield* revalidatePurchaseApprovalFromVerifiedOrder(transaction, scope, trusted, actionInvocationId);
    });
    return {
      read: (input: OrderServiceApprovalEvidenceRequest) =>
        read(input).pipe(
          Effect.flatMap(Schema.decodeUnknownEffect(Schema.toType(OrderServiceApprovalEvidenceResponseSchema))),
          Effect.mapError((failure) =>
            Predicate.isTagged(failure, 'PurchasingApprovalRejected') ? failure : unavailable(failure),
          ),
          Effect.provideContext(dependencies),
        ),
      revalidate: (payload: RevalidateOrderPurchaseApprovalPayload, actionInvocationId: string) =>
        revalidate(payload, actionInvocationId).pipe(Effect.provideContext(dependencies)),
    };
  },
);
