// AREA: visits (C02, C06) — owned by the crm-visits lane.
// Visits / calls / e-mails with correction history, and the manual contact plan ("K oslovení").
// Adding fields: make them Schema.optionalKey (persisted JSON from older revisions must still decode).
import { Schema } from 'effect';
import { EntityIdSchema, IsoTimeSchema, LongTextSchema, PrincipalIdSchema, ShortTextSchema } from './common.ts';

export const VisitKindSchema = Schema.Literals(['visit', 'call', 'email']);

/** A correction of a recorded visit; the visit is never overwritten without this trail (C02-03). */
export const VisitCorrectionSchema = Schema.Struct({
  at: IsoTimeSchema,
  by: PrincipalIdSchema,
  field: ShortTextSchema,
  next: Schema.optionalKey(LongTextSchema),
  previous: Schema.optionalKey(LongTextSchema),
});

export const VisitSchema = Schema.Struct({
  /** Principal who wrote the record. */
  authorPrincipalId: PrincipalIdSchema,
  clientId: EntityIdSchema,
  corrections: Schema.Array(VisitCorrectionSchema),
  createdAt: IsoTimeSchema,
  id: EntityIdSchema,
  kind: VisitKindSchema,
  nextStep: Schema.optionalKey(LongTextSchema),
  nextStepDate: Schema.optionalKey(IsoTimeSchema),
  note: Schema.optionalKey(LongTextSchema),
  /** When the visit really happened (not when it was typed in). */
  occurredAt: IsoTimeSchema,
  result: ShortTextSchema,
  /** Salesperson who made the visit; stays even when the client is reassigned later. */
  salespersonId: Schema.optionalKey(EntityIdSchema),
  updatedAt: IsoTimeSchema,
});
export type Visit = typeof VisitSchema.Type;

export const PlanItemStatusSchema = Schema.Literals(['open', 'done']);

/** Manual "ozvat se dne" item (C06). Never generated by the system. */
export const PlanItemSchema = Schema.Struct({
  clientId: EntityIdSchema,
  createdAt: IsoTimeSchema,
  createdBy: PrincipalIdSchema,
  doneAt: Schema.optionalKey(IsoTimeSchema),
  doneBy: Schema.optionalKey(PrincipalIdSchema),
  dueDate: IsoTimeSchema,
  id: EntityIdSchema,
  note: Schema.optionalKey(LongTextSchema),
  salespersonId: Schema.optionalKey(EntityIdSchema),
  status: PlanItemStatusSchema,
});
export type PlanItem = typeof PlanItemSchema.Type;

export const VisitsSliceSchema = Schema.Struct({
  items: Schema.Array(VisitSchema),
  plan: Schema.Array(PlanItemSchema),
});
export type VisitsSlice = typeof VisitsSliceSchema.Type;

export const initialVisitsSlice: VisitsSlice = { items: [], plan: [] };

/** Read projection: only visits / plan items of visible clients. */
export const projectVisitsSlice = (slice: VisitsSlice, visible: ReadonlySet<string>): VisitsSlice => ({
  items: slice.items.filter((visit) => visible.has(visit.clientId)),
  plan: slice.plan.filter((item) => visible.has(item.clientId)),
});
