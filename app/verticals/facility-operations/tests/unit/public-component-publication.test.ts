import { NodeServices } from '@effect/platform-node';
import { Effect, FileSystem } from 'effect';
import { expect, it } from 'effect-rstest';

import { RecordDiscussion } from '../../src/components/record-discussion.tsx';
import { facilityOperationsManifest } from '../../vertical.manifest.ts';

const verticalRoot = new URL('../../', import.meta.url).pathname;

const verticalSource = (file: string) =>
  Effect.gen(function* readVerticalSource() {
    const fileSystem = yield* FileSystem.FileSystem;
    return yield* fileSystem.readFileString(`${verticalRoot}${file}`);
  });

it.layer(NodeServices.layer)('facility-operations record-discussion public component publication', (test) => {
  test.effect('binds the manifest component and its Shell contribution to the federated artifact', () =>
    Effect.gen(function* manifestBinding() {
      expect(yield* verticalSource('vertical.manifest.ts')).toContain(
        "import { RecordDiscussion } from './src/components/record-discussion.tsx';",
      );
      expect(facilityOperationsManifest.publicSurface.components['record-discussion']).toBe(RecordDiscussion);
      const [contribution] = facilityOperationsManifest.publicSurface.shellContributions.publicComponents;
      expect(contribution?.componentKey).toBe('facility.operations.record-discussion');
      expect(contribution?.contributionKey).toBe('facility.operations.component.record-discussion');
      expect(contribution?.expose).toBe('./RecordDiscussion');
      expect(contribution?.entrypoint.entrypointKey).toBe('facility.operations.component.record-discussion');
      expect(contribution?.entrypoint.moduleKey).toBe('facility.operations');
      expect(contribution?.entrypoint.role).toBe('public_component');
      expect(contribution?.entrypoint.scope).toBe('tenant');
    }),
  );

  test.effect('reserves the private lazy registration binding and the Module Federation exposure', () =>
    Effect.gen(function* reservedSlots() {
      expect(yield* verticalSource('vertical.registration.ts')).toContain(
        "'record-discussion': () => import('./src/components/record-discussion.tsx'),",
      );
      expect(yield* verticalSource('module-federation.config.ts')).toContain(
        "'./RecordDiscussion': './src/components/record-discussion.tsx',",
      );
    }),
  );

  test.effect('keeps the Codesmith public-component header and the federated default export on the artifact', () =>
    Effect.gen(function* generatedHeader() {
      const artifact = yield* verticalSource('src/components/record-discussion.tsx');
      expect(artifact.startsWith('// @generated by OntOS Codesmith public-component v1\n')).toBe(true);
      expect(artifact).toContain('export const RecordDiscussion =');
      expect(artifact).toContain('export default RecordDiscussion;');
    }),
  );
});
