import type { ReadHandlerContext } from '@app/core-runtime';
import { defineRead, defineTenantModuleEntrypoint } from '@app/core-runtime';
import { Effect } from 'effect';

import {
  CounterpartyReadRequestSchema,
  CounterpartyReadResponseSchema,
} from '../../shared/apis/counterparty-read.ts';
import type { CounterpartyReadResponse } from '../../shared/apis/counterparty-read.ts';
import type { CounterpartyPersistenceUnavailable } from '../../shared/domain/counterparty-errors.ts';
import { findCounterpartyRecord } from '../services/counterparty-persistence.service.ts';
import type { LookupResult } from '../services/counterparty-persistence.service.ts';
// @generated by OntOS Codesmith module-api v1
import {
  counterpartyPermissionTarget,
  resolveCounterpartyRead,
} from './counterparty-read-support.ts';

const counterpartyReadEntrypoint = defineTenantModuleEntrypoint({
  access: 'read',
  authorization: { kind: 'context_permission', permission: 'module.access' },
  entrypointKey: 'party.registry.api.counterparty-read',
  moduleKey: 'party.registry',
  role: 'api',
});

export const counterpartyReadPermissionTarget = (
  input: Parameters<typeof counterpartyPermissionTarget>[0]
) => counterpartyPermissionTarget(input);

export const counterpartyReadRead = defineRead(
  {
    accessKind: 'detail',
    entrypoint: counterpartyReadEntrypoint,
    evidencePolicy: {
      captureMode: 'metadata_only',
      policyKey: 'party.registry.api.counterparty-read.evidence.v1',
    },
    inputSchema: CounterpartyReadRequestSchema,
    legalEntityScope: 'optional',
    owningModuleKey: 'party.registry',
    permissionTarget: 'resource',
    policies: [],
    readKey: 'party.registry.api.counterparty-read',
    resultSchema: CounterpartyReadResponseSchema,
    schemaVersion: '1',
  },
  (
    input,
    context: ReadHandlerContext<{
      readonly find: (
        counterpartyId: string
      ) => Effect.Effect<
        LookupResult<CounterpartyReadResponse>,
        CounterpartyPersistenceUnavailable
      >;
    }>
  ) =>
    resolveCounterpartyRead(
      input.counterpartyRef,
      context.scope.tenantId,
      context.services.find,
      'Counterparty persistence is temporarily unavailable'
    ).pipe(
      Effect.map((value) => ({ evidence: { resultCount: 1 }, result: value }))
    ),
  (transaction, scope) =>
    Effect.succeed({
      find: (counterpartyId: string) =>
        findCounterpartyRecord(
          transaction,
          scope.tenantId,
          scope.legalEntityId,
          counterpartyId
        ),
    }),
  counterpartyReadPermissionTarget
);
