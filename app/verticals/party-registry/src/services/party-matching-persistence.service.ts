export const resolveDuplicateCandidateCreate: ResolveDuplicateCandidateCreateOperation = Effect.fn(
  'PartyMatchingPersistenceService.resolveDuplicateCandidateCreate',
)(function* resolveCreate(
  transaction: Parameters<ResolveDuplicateCandidateCreateOperation>[0],
  input: Parameters<ResolveDuplicateCandidateCreateOperation>[1],
) {
  yield* lockTenantIdentityWrites(transaction, input.tenantId);
  const candidateCase = yield* requireOpenCandidateCase(transaction, input);
  if (candidateCase.candidateSnapshot.intent === 'UNARCHIVE') {
    return yield* new DuplicateCandidateConflict({
      code: 'duplicate_candidate_conflict',
      reason: 'Unarchive review must preserve the existing Party; Candidate creation cannot replace it',
    });
  }
  if (
    candidateCase.candidateSnapshot.provenance === undefined ||
    candidateCase.candidateSnapshot.validFrom === undefined
  ) {
    return yield* new DuplicateCandidateConflict({
      code: 'duplicate_candidate_conflict',
      reason: 'The Candidate snapshot lacks its original provenance or effective time',
    });
  }
  const candidate = yield* restoreCandidate(candidateCase.candidateSnapshot);
  if (candidate.officialIdentifiers.some((identifier) => identifier.identifierType === 'ICO')) {
    yield* requireLegacyIcoAuthority(transaction, input.tenantId).pipe(Effect.mapError(unavailable));
  }
  yield* requireSupportedPartyEvidenceOperation(candidate.subjectEvidence, 'REVIEW', input.sourceScope, {
    kind: 'DUPLICATE_CANDIDATE',
    caseId: input.candidateCaseId,
  });
  const createInput: Parameters<typeof createOrMatchParty>[1] = {
    actionInvocationId: input.actionInvocationId,
    candidate,
    createWithoutStrongIdentifierReviewed: true,
    operation: 'REVIEW_CREATE',
    principalId: input.principalId,
    tenantId: input.tenantId,
  };
  if (input.sourceScope !== undefined) {
    Object.assign(createInput, { sourceScope: input.sourceScope });
  }
  if (input.legalEntityId !== undefined) {
    Object.assign(createInput, { legalEntityId: input.legalEntityId });
  }
  const result: PartyCreateOutcome & {
    readonly addedOfficialIdentifierRefs?: readonly PartyOfficialIdentifierRef[];
  } = yield* createOrMatchParty(transaction, createInput);
  if (result.outcome !== 'CREATED') {
    return yield* new DuplicateCandidateConflict({
      code: 'duplicate_candidate_conflict',
      reason: 'Canonical recheck does not permit creating a new Party',
    });
  }
  const now = yield* DateTime.nowAsDate;
  yield* transaction
    .update(duplicateCandidateCases)
    .set({
      lifecycleState: 'RESOLVED',
      resolutionActionInvocationId: input.actionInvocationId,
      resolutionOutcome: 'CREATE_NEW',
      resolutionReason: input.reason,
      resolvedAt: now,
      revision: candidateCase.revision + 1,
      selectedPartyId: result.partyRef.resourceId,
      updatedAt: now,
    })
    .where(
      and(
        eq(duplicateCandidateCases.tenantId, input.tenantId),
        eq(duplicateCandidateCases.candidateCaseId, input.candidateCaseId),
      ),
    )
    .pipe(Effect.mapError(unavailable));
  return {
    caseRef: makeDuplicateCandidateCaseRef(input.tenantId, input.candidateCaseId),
    decisionRef: result.decisionRef,
    lifecycleState: 'RESOLVED',
    outcome: 'CREATE_NEW',
    partyRef: result.partyRef,
  } as const;
});

