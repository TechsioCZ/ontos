export const candidateFingerprint = (candidate: PartyCandidate): string =>
  Hex.encode(
    sha256(
      utf8ToBytes(
        encodeJson({
          firstName: candidate.firstName ?? null,
          lastName: candidate.lastName ?? null,
          businessName: candidate.businessName ?? null,
          evidenceEvaluation: {
            ...evaluatePartySubjectEvidence(candidate),
            evidence: (candidate.subjectEvidence ?? [])
              .map((item) =>
                encodeJson(
                  canonicalFingerprintJson(Result.getOrThrow(Schema.encodeResult(PartySubjectEvidenceSchema)(item))),
                ),
              )
              .toSorted(),
          },
          evidenceRefs: [...candidate.evidenceRefs].toSorted(),
          officialIdentifiers: candidate.officialIdentifiers
            .map(normalizeOfficialIdentifier)
            .toSorted((left, right) =>
              `${left.identifierType}\u0000${left.namespace}\u0000${left.normalizedValue}`.localeCompare(
                `${right.identifierType}\u0000${right.namespace}\u0000${right.normalizedValue}`,
                'en',
              ),
            ),
          partyType: candidate.partyType,
          provenance: {
            externalEvidence:
              candidate.provenance.externalEvidence === undefined
                ? null
                : Object.fromEntries(
                    Object.entries(candidate.provenance.externalEvidence).toSorted(([left], [right]) =>
                      left.localeCompare(right, 'en'),
                    ),
                  ),
            method: candidate.provenance.method,
            source: candidate.provenance.source,
          },
          validFrom: encodedCandidateInstant(candidate.validFrom),
        }),
      ),
    ),
  );

/** Replay compares accepted source input independently of today's eligibility rules. */
const createCandidateFingerprint = (candidate: PartyCandidate): string => {
  if (clientSourceAssertion(candidate.subjectEvidence) === undefined) {
    return candidateFingerprint(candidate);
  }
  const sourceInput = Result.getOrThrow(Schema.encodeResult(PartyCandidateSchema)(candidate));
  return Hex.encode(sha256(utf8ToBytes(encodeJson(canonicalFingerprintJson(sourceInput)))));
};

