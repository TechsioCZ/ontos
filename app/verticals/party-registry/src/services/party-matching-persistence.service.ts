export const findSourceCreateReceipt = Effect.fn('PartyMatchingPersistenceService.findSourceCreateReceipt')(
  function* findReceipt(
    transaction: Pick<PartyTransaction, 'select'>,
    scope: PartyClientSourceScope,
    actionInvocationId: string,
  ) {
    const [receipt] = yield* transaction
      .select()
      .from(partyCreateSourceReceipts)
      .where(
        and(
          eq(partyCreateSourceReceipts.tenantId, scope.tenantId),
          eq(partyCreateSourceReceipts.actionInvocationId, actionInvocationId),
        ),
      )
      .limit(1)
      .pipe(Effect.mapError(unavailable));
    if (receipt === undefined) {
      return;
    }
    if (receipt.principalId !== scope.principalId || receipt.legalEntityId !== (scope.legalEntityId ?? null)) {
      return yield* unavailable();
    }
    const [decision] = yield* transaction
      .select()
      .from(partyMatchDecisions)
      .where(
        and(
          eq(partyMatchDecisions.tenantId, scope.tenantId),
          eq(partyMatchDecisions.matchDecisionId, receipt.matchDecisionId),
        ),
      )
      .limit(1)
      .pipe(Effect.mapError(unavailable));
    if (decision === undefined) {
      return yield* unavailable();
    }
    const evidence = yield* Schema.decodeUnknownEffect(PartyEvidenceEvaluationSchema)(decision.evidenceEvaluation).pipe(
      Effect.mapError(unavailable),
    );
    const source = clientSourceAssertion(evidence.evidence);
    if (source === undefined) {
      return yield* unavailable();
    }
    const original = yield* findPartySourceDecision(transaction, scope.tenantId, source, true);
    if (original?.matchDecisionId !== decision.matchDecisionId) {
      return yield* unavailable();
    }
    yield* authorizeSourceCreateRecovery(transaction, source, scope, decision);
    return decision;
  },
);

const decisionEvidenceTargets = (row: typeof partyMatchDecisions.$inferSelect): readonly PartySourceCreateTarget[] => {
  if (row.partyId !== null) {
    return [{ kind: 'PARTY', partyId: row.partyId }];
  }
  if (row.candidateCaseId !== null) {
    return [{ kind: 'DUPLICATE_CANDIDATE', caseId: row.candidateCaseId }];
  }
  return [];
};
const authorizeDecisionEvidenceRead = Effect.fn('PartyMatchingPersistenceService.authorizeDecisionEvidenceRead')(
  function* authorizeRead(
    transaction: Pick<PartyTransaction, 'select'>,
    tenantId: string,
    row: typeof partyMatchDecisions.$inferSelect,
    sourceScope?: PartyClientSourceScope,
  ) {
    yield* requireSupportedPartyEvidenceOperation(row.evidenceEvaluation?.evidence, 'EVIDENCE_READ', sourceScope);
    const evidence =
      row.evidenceEvaluation === null
        ? undefined
        : yield* Schema.decodeUnknownEffect(PartyEvidenceEvaluationSchema)(row.evidenceEvaluation).pipe(
            Effect.mapError(unavailable),
          );
    yield* authorizeSourceTargets(
      clientSourceAssertion(evidence?.evidence),
      sourceScope,
      'EVIDENCE_READ',
      decisionEvidenceTargets(row),
    ).pipe(Effect.mapError(unavailable));
    if (row.candidateCaseId !== null) {
      const partyIds = yield* findCasePartyIds(transaction, tenantId, row.candidateCaseId);
      yield* authorizeSourceTargets(
        clientSourceAssertion(evidence?.evidence),
        sourceScope,
        'EVIDENCE_READ',
        partyIds.map((partyId) => ({ kind: 'PARTY', partyId })),
      ).pipe(Effect.mapError(unavailable));
    }
    if (sourceScope?.tenantId === tenantId) {
      // An erased evidence payload does not turn an existing source decision into generic read data.
      const [sourceReceipt] = yield* transaction
        .select({ actionInvocationId: partyCreateSourceReceipts.actionInvocationId })
        .from(partyCreateSourceReceipts)
        .where(
          and(
            eq(partyCreateSourceReceipts.tenantId, tenantId),
            eq(partyCreateSourceReceipts.matchDecisionId, row.matchDecisionId),
          ),
        )
        .limit(1)
        .pipe(Effect.mapError(unavailable));
      if (sourceReceipt !== undefined && evidence === undefined) {
        return yield* unavailable();
      }
    }
  },
);

export const findMatchDecision = Effect.fn('PartyMatchingPersistenceService.findMatchDecision')(function* findDecision(
  transaction: Pick<PartyTransaction, 'select'>,
  tenantId: string,
  input: { readonly actionInvocationId?: string; readonly decisionId?: string },
  sourceScope?: PartyClientSourceScope,
) {
  const recovery =
    input.actionInvocationId !== undefined && input.decisionId === undefined && sourceScope?.tenantId === tenantId
      ? yield* findSourceCreateReceipt(transaction, sourceScope, input.actionInvocationId)
      : undefined;
  const [row] =
    recovery === undefined
      ? yield* transaction
          .select()
          .from(partyMatchDecisions)
          .where(
            and(
              eq(partyMatchDecisions.tenantId, tenantId),
              input.decisionId === undefined
                ? eq(partyMatchDecisions.actionInvocationId, input.actionInvocationId ?? '')
                : eq(partyMatchDecisions.matchDecisionId, input.decisionId),
            ),
          )
          .limit(1)
          .pipe(Effect.mapError(unavailable))
      : [recovery];
  if (row === undefined) {
    return { _tag: 'not_found' } as const;
  }
  if (recovery === undefined) {
    yield* authorizeDecisionEvidenceRead(transaction, tenantId, row, sourceScope);
  }
  return {
    _tag: 'found',
    value: {
      caseRef: row.candidateCaseId === null ? null : makeDuplicateCandidateCaseRef(tenantId, row.candidateCaseId),
      // SAFETY: Database CHECK constrains committed Create results.
      committedCreateOutcome: row.committedCreateOutcome as 'CREATED' | 'MATCHED_EXISTING' | 'AMBIGUOUS' | null,
      decidedAt: row.decidedAt.toISOString(),
      decisionRef: makePartyMatchDecisionRef(tenantId, row.matchDecisionId),
      // The invocation receipt authorizes recovery of references and outcome only.
      evidenceEvaluation: recovery === undefined ? row.evidenceEvaluation : null,
      evidenceExplanation: recovery === undefined ? row.evidenceExplanation.map((item) => ({ ...item })) : [],
      matchRuleVersion: row.matchRuleVersion,
      // SAFETY: Database CHECKs constrain operation and committed Create result.
      operation: row.operation as 'CREATE' | 'MATCH' | 'REVIEW_MATCH' | 'REVIEW_CREATE' | 'LIFECYCLE' | 'LEGACY',
      // SAFETY: The owner-local decision outcome CHECK admits exactly these outcomes.
      outcome: row.outcome as 'CREATED' | 'MATCHED' | 'NO_MATCH' | 'AMBIGUOUS',
      partyRef: row.partyId === null ? null : makePartyRef(tenantId, row.partyId),
    },
  } as const;
});

export const findDuplicateCandidateCase = Effect.fn('PartyMatchingPersistenceService.findDuplicateCandidateCase')(
  function* findCase(
    transaction: Pick<PartyTransaction, 'select'>,
    tenantId: string,
    caseId: string,
    sourceScope?: PartyClientSourceScope,
  ) {
    const [record] = yield* transaction
      .select()
      .from(duplicateCandidateCases)
      .where(and(eq(duplicateCandidateCases.tenantId, tenantId), eq(duplicateCandidateCases.candidateCaseId, caseId)))
      .limit(1);
    if (record === undefined) {
      return { _tag: 'not_found' } as const;
    }
    if (record.candidateSnapshot.subjectEvidence?.some((item) => item.kind === 'CLIENT_SOURCE_ASSERTION') !== true) {
      const [sourceReceipt] = yield* transaction
        .select({ actionInvocationId: partyCreateSourceReceipts.actionInvocationId })
        .from(partyCreateSourceReceipts)
        .innerJoin(
          partyMatchDecisions,
          and(
            eq(partyMatchDecisions.tenantId, partyCreateSourceReceipts.tenantId),
            eq(partyMatchDecisions.matchDecisionId, partyCreateSourceReceipts.matchDecisionId),
          ),
        )
        .where(and(eq(partyCreateSourceReceipts.tenantId, tenantId), eq(partyMatchDecisions.candidateCaseId, caseId)))
        .limit(1);
      if (sourceReceipt !== undefined) {
        return yield* unavailable();
      }
    }
    yield* requireSupportedPartyEvidenceOperation(
      record.candidateSnapshot.subjectEvidence,
      'EVIDENCE_READ',
      sourceScope,
      { kind: 'DUPLICATE_CANDIDATE', caseId },
    );
    const candidatePartyIds = yield* findCasePartyIds(transaction, tenantId, caseId);
    yield* Effect.forEach(
      candidatePartyIds,
      (partyId) =>
        requireSupportedPartyEvidenceOperation(record.candidateSnapshot.subjectEvidence, 'EVIDENCE_READ', sourceScope, {
          kind: 'PARTY',
          partyId,
        }),
      { concurrency: 1, discard: true },
    );
    return {
      _tag: 'found',
      value: {
        candidate: {
          ...candidateNameFields(record.candidateSnapshot),
          evidenceRefs: record.candidateSnapshot.evidenceArtifactRefs ?? [],
          officialIdentifiers: (record.candidateSnapshot.officialIdentifiers ?? []).map((identifier) => ({
            identifierType: identifier.identifierTypeKey,
            value: identifier.normalizedValue,
          })),
          partyType: record.candidateSnapshot.partyType ?? 'UNRESOLVED',
          provenance: record.candidateSnapshot.provenance,
          subjectEvidence: record.candidateSnapshot.subjectEvidence ?? [],
          validFrom: record.candidateSnapshot.validFrom,
        },
        candidateParties: candidatePartyIds.map((partyId) => makePartyRef(tenantId, partyId)),
        caseRef: makeDuplicateCandidateCaseRef(tenantId, caseId),
        evaluatedEvidence: record.evaluatedEvidence.map((evidence) => ({
          ...evidence,
        })),
        // SAFETY: The owner-local case lifecycle CHECK admits exactly these states.
        lifecycleState: record.lifecycleState as 'OPEN' | 'NEEDS_EVIDENCE' | 'RESOLVED' | 'DISMISSED',
        matchRuleVersion: record.matchRuleVersion,
        priorCaseRef:
          record.priorCandidateCaseId === null
            ? null
            : makeDuplicateCandidateCaseRef(tenantId, record.priorCandidateCaseId),
        resolutionOutcome: record.resolutionOutcome,
        resolutionReason: record.resolutionReason,
        resolvedAt: record.resolvedAt?.toISOString() ?? null,
        revision: record.revision,
      },
    } as const;
  },
  Effect.mapError(unavailable),
);

const mutationReceiptDetails = Effect.fn('PartySourceReceipt.mutationDetails')(function* mutationDetails(
  input: Extract<PartySourceEffectReceiptRequest, { readonly operation: 'UPDATE' | 'CORRECTION' }>,
) {
  if (input.operation === 'UPDATE') {
    return { partyId: input.payload.partyRef.resourceId, evidence: input.payload.subjectEvidence };
  }
  if (input.payload.factKind === 'RELATIONSHIP') {
    return yield* unavailable();
  }
  return { partyId: input.payload.partyId, evidence: input.payload.subjectEvidence };
});

const recoverIdentitySourceEffect = Effect.fn('PartySourceReceipt.recoverIdentity')(function* recoverIdentity(
  transaction: Pick<PartyTransaction, 'select'>,
  scope: PartyClientSourceScope,
  input: Extract<PartySourceEffectReceiptRequest, { readonly operation: 'CREATE' | 'MATCH' }>,
) {
  const { candidate } = input.payload;
  const assertion = clientSourceAssertion(candidate.subjectEvidence);
  if (assertion === undefined) {
    return yield* unavailable();
  }
  const organizationProjection = yield* authorizePartyEvidenceWithProjection(candidate.subjectEvidence, scope, {
    operation: 'EVIDENCE_READ',
  });
  if (organizationProjection === true) {
    return yield* recoverOrganizationSourceEffect(transaction, scope, input);
  }
  const decision =
    input.operation === 'CREATE'
      ? yield* findPartySourceDecision(transaction, scope.tenantId, assertion, true)
      : yield* findPartySourceMatchDecision(transaction, scope.tenantId, assertion);
  if (decision === undefined) {
    return { outcome: 'INDETERMINATE' as const };
  }
  let fingerprint = createCandidateFingerprint(candidate);
  if (input.operation === 'MATCH') {
    const matchInput: MatchPartyInput = {
      actionInvocationId: decision.actionInvocationId,
      candidate,
      tenantId: scope.tenantId,
    };
    if (input.payload.priorCaseRef !== undefined) {
      Object.assign(matchInput, {
        priorCandidateCaseId: input.payload.priorCaseRef.resourceId,
        priorCaseTenantId: input.payload.priorCaseRef.tenantId,
      });
    }
    fingerprint = sourceMatchRequestFingerprint(matchInput);
  }
  if (decision.candidateFingerprint !== fingerprint) {
    return yield* new PartyEvidenceInsufficient({
      code: 'party_evidence_insufficient',
      reason: 'client_source_effect_identity_conflict',
    });
  }
  const [receipt] = yield* transaction
    .select()
    .from(partyCreateSourceReceipts)
    .where(
      and(
        eq(partyCreateSourceReceipts.tenantId, scope.tenantId),
        eq(partyCreateSourceReceipts.actionInvocationId, decision.actionInvocationId),
      ),
    )
    .limit(1)
    .pipe(Effect.mapError(unavailable));
  if (receipt === undefined) {
    return { outcome: 'INDETERMINATE' as const };
  }
  if (receipt.principalId !== scope.principalId || receipt.legalEntityId !== (scope.legalEntityId ?? null)) {
    return yield* unavailable();
  }
  if (input.operation === 'MATCH') {
    const result = yield* sourceMatchDecisionResult(transaction, scope.tenantId, decision, scope);
    return {
      outcome: 'COMMITTED' as const,
      operation: 'MATCH' as const,
      actionInvocationId: decision.actionInvocationId,
      result,
    };
  }
  const recovered = yield* findSourceCreateReceipt(transaction, scope, decision.actionInvocationId);
  if (recovered === undefined) {
    return { outcome: 'INDETERMINATE' as const };
  }
  const result = {
    decisionRef: makePartyMatchDecisionRef(scope.tenantId, decision.matchDecisionId),
    outcome: decision.committedCreateOutcome,
    ...(decision.partyId === null
      ? { caseRef: makeDuplicateCandidateCaseRef(scope.tenantId, decision.candidateCaseId ?? '') }
      : { partyRef: makePartyRef(scope.tenantId, decision.partyId) }),
  };
  const decoded = yield* Schema.decodeUnknownEffect(PartyCreateOutcomeSchema)(result).pipe(
    Effect.mapError(unavailable),
  );
  return {
    outcome: 'COMMITTED' as const,
    operation: 'CREATE' as const,
    actionInvocationId: decision.actionInvocationId,
    result: decoded,
  };
});

const recoverMutationSourceEffect = Effect.fn('PartySourceReceipt.recoverMutation')(function* recoverMutation(
  transaction: Pick<PartyTransaction, 'select'>,
  scope: PartyClientSourceScope,
  input: Extract<PartySourceEffectReceiptRequest, { readonly operation: 'UPDATE' | 'CORRECTION' }>,
) {
  const details = yield* mutationReceiptDetails(input);
  const { evidence, partyId } = details;
  if (clientSourceAssertion(evidence) === undefined) {
    return yield* unavailable();
  }
  if (input.operation === 'UPDATE' && input.payload.partyRef.tenantId !== scope.tenantId) {
    return yield* unavailable();
  }
  const request =
    input.operation === 'UPDATE'
      ? yield* Schema.encodeEffect(UpdatePartyPayloadSchema)(input.payload).pipe(Effect.mapError(unavailable))
      : yield* Schema.encodeUnknownEffect(CorrectPartyFactPayloadSchema)(input.payload).pipe(
          Effect.mapError(unavailable),
        );
  const prepared = yield* preparePartySourceEffect(
    transaction,
    {
      tenantId: scope.tenantId,
      principalId: scope.principalId,
      partyId,
      subjectEvidence: evidence,
      sourceScope: scope,
      operation: input.operation,
      request,
    },
    'RECOVER',
  );
  const receipt = prepared?.receipt;
  if (receipt === undefined) {
    return { outcome: 'INDETERMINATE' as const };
  }
  if (input.operation === 'UPDATE') {
    const result = yield* Schema.decodeUnknownEffect(PartySourceUpdateReceiptResultSchema)(receipt.result).pipe(
      Effect.mapError(unavailable),
    );
    return {
      outcome: 'COMMITTED' as const,
      operation: 'UPDATE' as const,
      actionInvocationId: receipt.actionInvocationId,
      result,
    };
  }
  const result = yield* Schema.decodeUnknownEffect(CorrectPartyFactResultSchema)(receipt.result).pipe(
    Effect.mapError(unavailable),
  );
  return {
    outcome: 'COMMITTED' as const,
    operation: 'CORRECTION' as const,
    actionInvocationId: receipt.actionInvocationId,
    result,
  };
});

/** Exact original source commands recover committed effects without resubmission. */
export const recoverPartySourceEffectReceipt = Effect.fn('PartySourceReceipt.recover')(function* recover(
  transaction: Pick<PartyTransaction, 'select'>,
  scope: PartyClientSourceScope,
  input: Extract<PartySourceEffectReceiptRequest, { readonly operation: 'CREATE' | 'MATCH' | 'UPDATE' | 'CORRECTION' }>,
) {
  if (input.operation === 'CREATE' || input.operation === 'MATCH') {
    return yield* recoverIdentitySourceEffect(transaction, scope, input);
  }
  return yield* recoverMutationSourceEffect(transaction, scope, input);
});
