const persistDecision = (
  transaction: Pick<PartyTransaction, 'insert'>,
  input: {
    readonly actionInvocationId: string;
    readonly candidateCaseId?: string;
    readonly candidateFingerprint: string;
    readonly candidate: PartyCandidate;
    readonly confirmedSource?: boolean;
    readonly outcome: 'CREATED' | 'MATCHED' | 'NO_MATCH' | 'AMBIGUOUS';
    readonly operation: 'CREATE' | 'MATCH' | 'REVIEW_MATCH' | 'REVIEW_CREATE';
    readonly partyId?: string;
    readonly partyIds: readonly string[];
    readonly reviewedCaseId?: string;
    readonly tenantId: string;
  },
) =>
  Schema.encodeEffect(PartyEvidenceEvaluationSchema)(decisionEvidenceEvaluation(input.candidate)).pipe(
    Effect.mapError(unavailable),
    Effect.flatMap((evidenceEvaluation) => {
      const evidenceExplanation =
        input.confirmedSource === true
          ? [
              {
                evidenceRefs: [...input.candidate.evidenceRefs].toSorted(),
                outcome: 'MATCHED' as const,
                reason: 'An accepted qualified source record identifies this Party',
                ruleKey: MATCH_RULE_VERSION,
              },
            ]
          : explainCandidateEvidence(input.candidate, input.outcome);
      const values: typeof partyMatchDecisions.$inferInsert = {
        actionInvocationId: input.actionInvocationId,
        candidateFingerprint: input.candidateFingerprint,
        committedCreateOutcome: null,
        evidenceEvaluation,
        evidenceExplanation,
        matchRuleVersion: MATCH_RULE_VERSION,
        operation: input.operation,
        outcome: input.outcome,
        tenantId: input.tenantId,
      };
      if (input.reviewedCaseId !== undefined) {
        values.evidenceExplanation = [
          ...evidenceExplanation,
          {
            outcome: 'MATCHED',
            reason: 'Reused the unchanged explicit MATCH_EXISTING review',
            reviewedCaseRef: makeDuplicateCandidateCaseRef(input.tenantId, input.reviewedCaseId),
            ruleKey: MATCH_RULE_VERSION,
          },
        ];
      }
      if (input.operation === 'CREATE' || input.operation === 'REVIEW_CREATE') {
        values.committedCreateOutcome = input.outcome === 'MATCHED' ? 'MATCHED_EXISTING' : input.outcome;
      }
      if (input.candidateCaseId !== undefined) {
        values.candidateCaseId = input.candidateCaseId;
      }
      if (input.partyId !== undefined) {
        values.partyId = input.partyId;
      }
      return transaction
        .insert(partyMatchDecisions)
        .values(values)
        .returning()
        .pipe(
          Effect.mapError(unavailable),
          Effect.flatMap(([decision]) =>
            decision === undefined ? Effect.fail(unavailable()) : Effect.succeed(decision),
          ),
        );
    }),
  );

const collectNewIdentifierAcceptance = (
  acceptedIds: Set<string>,
  record: typeof partyOfficialIdentifiers.$inferSelect,
  actionInvocationId: string,
) => {
  // Core never reruns a committed invocation; this also deduplicates repeated Candidate facts
  // accepted earlier in the same transaction without republishing a prior invocation's facts.
  if (record.acceptedByActionInvocationId === actionInvocationId) {
    acceptedIds.add(record.officialIdentifierId);
  }
};

